import fs from 'node:fs';
import cp from 'node:child_process';
import assert from 'node:assert/strict';
const repo='worktrees/own-free-split';
const file='src/registry/heap_core/free/dealloc_own_base.rs';
const base=cp.execFileSync('git',['-C',repo,'show','f80c681b799ef4ef7fa08d79c06896fdf1104fe9:'+file],{encoding:'utf8'});
const next=fs.readFileSync(repo+'/'+file,'utf8');
const cap='                    // ── R1-01: free-side byte-budget cap reached';
const full='                    // ── Magazine overflow (cnt == TCACHE_CAP)';
const end='                    return;\n                }';
const beforeCap=base.slice(base.indexOf(cap),base.indexOf(full));
const afterCap=next.slice(next.indexOf(cap),next.indexOf('                    self.dealloc_full_magazine'));
assert.equal(afterCap,beforeCap);
assert.equal(next.slice(0,next.indexOf(cap)),base.slice(0,base.indexOf(cap)).replace('use crate::registry::heap_core::state::tcache::{FLUSH_N, FREE_PARK_CAP, TCACHE_CAP};','use crate::registry::heap_core::state::tcache::{FREE_PARK_CAP, TCACHE_CAP};'));
const oldFull=base.slice(base.indexOf(full),base.indexOf(end,base.indexOf(full))).split('\n').map(l=>l.startsWith('                    ')?l.slice(12):l).join('\n').trim();
const newStart=next.indexOf('        // ── Magazine overflow (cnt == TCACHE_CAP)');
const newFull=next.slice(newStart,next.lastIndexOf('    }')).trim();
assert.equal(newFull,oldFull);
console.log('PASS: guard/normal prefix, inline cap-eviction and moved half-flush body preserve baseline source.');
