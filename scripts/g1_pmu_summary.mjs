#!/usr/bin/env node
// G1 contemplation: PMU per-op table, sefer vs mimalloc, from the raw log
// written by docs/perf/g1_pmu/g1_pmu.sh. Median over repeats per
// (scenario, allocator, event); per-op = count / ops (ops include warm-up,
// identical for both allocators). Usage: node scripts/g1_pmu_summary.mjs <log>
import fs from "node:fs";

const log = process.argv[2];
if (!log) throw new Error("usage: g1_pmu_summary.mjs <log>");
const lines = fs.readFileSync(log, "utf8").split("\n");

// ops per process, by the probe's own warm-up rules (examples/b4_pmu_probe.rs)
function opsOf(argv) {
  const [mode, , ...r] = argv;
  if (mode === "bulk") {
    const [n, , passes] = r.map(Number);
    return 2 * n * (passes + Math.max(Math.floor(passes / 10), 4));
  }
  if (mode === "mixed") {
    // printed: live size/size2 portion done (done = measured ops, whole portions)
    const [live, , portion, done] = r.map(Number);
    const rnd = (t) => Math.ceil(t / portion) * portion;
    return 2 * (live + rnd(Math.max(Math.floor(done / 10), 10000)) + done);
  }
  const [live, , ops] = r.map(Number);
  return 2 * (live + Math.max(Math.floor(ops / 10), 10000) + ops);
}

const ops = new Map(); // scenario -> ops
const ns = new Map(); // scenario|alloc -> [ns_per_op]
const ev = new Map(); // scenario|alloc|event -> [count]
for (const l of lines) {
  const f = l.trim().split(/\s+/);
  if (f[0] === "RUN") {
    const [, , sc, a, , ...out] = f;
    const argv = out.slice(0, -2);
    const o = opsOf(argv[0] === "bulk" || argv[0] === "mixed" ? argv : ["churn", ...argv]);
    if (ops.has(sc) && ops.get(sc) !== o) throw new Error(`ops mismatch ${sc}`);
    ops.set(sc, o);
    const k = `${sc}|${a}`;
    if (!ns.has(k)) ns.set(k, []);
    ns.get(k).push(Number(out[out.length - 2]));
  } else if (f[0] === "EV") {
    const [, , sc, a, , name, val] = f;
    const n = Number(val);
    if (!Number.isFinite(n)) throw new Error(`not counted: ${l}`);
    const e = name.replace(/:u$/, "");
    const k = `${sc}|${a}|${e}`;
    if (!ev.has(k)) ev.set(k, []);
    ev.get(k).push(n);
  }
}
const med = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};
const events = [...new Set([...ev.keys()].map((k) => k.split("|")[2]))];
const scen = [...ops.keys()];
const out = [];
out.push(`# G1 PMU per op (median of repeats; generated by scripts/g1_pmu_summary.mjs from ${log.split(/[\/]/).pop()})`);
out.push("");
out.push(`| scenario | metric | sefer | mimalloc | sefer/mi |`);
out.push(`|---|---|---:|---:|---:|`);
const csv = ["scenario,metric,sefer,mimalloc,ratio"];
for (const sc of scen) {
  const rows = [["ns/op (probe clock)", med(ns.get(`${sc}|sefer`)), med(ns.get(`${sc}|mi`))]];
  for (const e of events) {
    const s = ev.get(`${sc}|sefer|${e}`), m = ev.get(`${sc}|mi|${e}`);
    if (!s || !m) continue;
    rows.push([`${e}/op`, med(s) / ops.get(sc), med(m) / ops.get(sc)]);
  }
  for (const [name, s, m] of rows) {
    const r = s / m;
    if (!Number.isFinite(r)) throw new Error(`bad ratio ${sc} ${name}`);
    out.push(`| ${sc} | ${name} | ${s.toFixed(3)} | ${m.toFixed(3)} | ${r.toFixed(3)} |`);
    csv.push(`${sc},${name},${s},${m},${r}`);
  }
}
console.log(out.join("\n"));
if (process.argv[3]) fs.writeFileSync(process.argv[3], csv.join("\n") + "\n");
