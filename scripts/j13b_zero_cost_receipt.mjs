for (const [name, content] of [
  ['J13B_TASK78_ZERO_COST_RECEIPT_summary.csv', csv],
  ['J13B_TASK78_ZERO_COST_RECEIPT.md', md],
]) {
  const path = resolve(root, 'docs/perf', name);
  if (process.argv.includes('--check')) assert.equal(readFileSync(path, 'utf8'), content, `stale ${name}`);
  else writeFileSync(path, content);
}
console.log('[j13b-zero-cost-receipt] structured identity, exact arithmetic and derived artifacts OK');
