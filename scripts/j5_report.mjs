// J5: derives docs/perf/J5_WINDOWS_JUDGE_MAP.md and docs/perf/J5_WINDOWS_JUDGE_MAP_summary.csv from docs/perf/j5/win_raw.jsonl
// (written by `node docs/perf/wg1/run.mjs <exe> docs/perf/j5/win_raw.jsonl 12 3`), next to the WG-1 reading in
// docs/perf/WG1_WINDOWS_MAP_AFTER_AO1_summary.csv. Asserts every printed number.
// Per block and arm the minimum ns/op over the repeats; per block d = ln(sefer / mi); the cell is exp(mean d) with a
// two-sided 95 % t-interval (n - 1 degrees of freedom).
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const dir = new URL('../docs/perf/', import.meta.url);
const rd = (p) => readFileSync(new URL(p, dir), 'utf8');
const T975 = { 3: 3.182, 5: 2.571, 7: 2.365, 9: 2.262, 11: 2.201, 15: 2.131 };
const SCEN = ['grow64', 'grow1k', 'regrow', 'growmix', 'wild', 'phase', 'large'];
const recs = rd('j5/win_raw.jsonl').trim().split(/\r?\n/).map((l) => JSON.parse(l));
const ident = rd('j5/ident.txt').trim().split(/\r?\n/);
const sha = /^main ([0-9a-f]{40})$/.exec(ident[0]);
assert.ok(sha, 'ident: source SHA');
const bin = /^([0-9a-f]{64})\s/.exec(ident[1]);
assert.ok(bin, 'ident: binary sha256');
const prev = {};
for (const l of rd('WG1_WINDOWS_MAP_AFTER_AO1_summary.csv').trim().split(/\r?\n/).slice(1)) {
  const c = l.split(',');
  prev[c[0]] = { r: +c[1], lo: +c[2], hi: +c[3] };
}
const blocks = [...new Set(recs.map((r) => r.block))].sort((a, b) => a - b);
const t = T975[blocks.length - 1];
assert.ok(t, `no t quantile for n=${blocks.length}`);
assert.deepEqual([...new Set(recs.map((r) => r.r.scenario))].sort(), [...SCEN].sort());
const f3 = (x) => x.toFixed(3);
const rows = [];
let csv = 'scenario,sefer_over_mi,ci_lo,ci_hi,verdict,wg1_sefer_over_mi,wg1_lo,wg1_hi,blocks,repeats\n';
for (const sc of SCEN) {
  const d = blocks.map((b) => {
    const mn = (arm) => {
      const v = recs.filter((r) => r.block === b && r.arm === arm && r.r.scenario === sc).map((r) => r.r.ns_per_op);
      assert.ok(v.length >= 1, `samples ${b} ${arm} ${sc}`);
      return Math.min(...v);
    };
    return Math.log(mn('sefer') / mn('mi'));
  });
  const n = d.length, m = d.reduce((a, b) => a + b, 0) / n;
  const sd = Math.sqrt(d.reduce((a, b) => a + (b - m) ** 2, 0) / (n - 1));
  const half = t * sd / Math.sqrt(n);
  const [r, lo, hi] = [Math.exp(m), Math.exp(m - half), Math.exp(m + half)];
  assert.ok(lo <= r && r <= hi, 'interval contains the estimate');
  const reps = recs.filter((x) => x.block === blocks[0] && x.arm === 'sefer' && x.r.scenario === sc).length;
  assert.ok(prev[sc], `WG-1 row for ${sc}`);
  const verdict = hi < 1 ? 'sefer ahead' : lo > 1 ? 'mimalloc ahead' : 'tie (interval contains 1)';
  assert.equal(verdict === 'mimalloc ahead', lo > 1, 'verdict');
  rows.push({ sc, r, lo, hi, verdict, n, reps });
  csv += `${sc},${f3(r)},${f3(lo)},${f3(hi)},${verdict},${f3(prev[sc].r)},${f3(prev[sc].lo)},${f3(prev[sc].hi)},${n},${reps}\n`;
}
writeFileSync(new URL('J5_WINDOWS_JUDGE_MAP_summary.csv', dir), csv);
const behind = rows.filter((x) => x.verdict === 'mimalloc ahead');
const ahead = rows.filter((x) => x.verdict === 'sefer ahead');
const tied = rows.filter((x) => x.verdict.startsWith('tie'));
assert.equal(behind.length + ahead.length + tied.length, SCEN.length);
const table = rows.map((x) => `| ${x.sc} | ${f3(x.r)} | ${f3(x.lo)}–${f3(x.hi)} | ${x.verdict} | ${f3(prev[x.sc].r)} | ${f3(prev[x.sc].lo)}–${f3(prev[x.sc].hi)} | ${x.n} x ${x.reps} |`).join('\n');
const worst = [...rows].sort((a, b) => b.r - a.r).slice(0, 3).map((x) => `${x.sc} ${f3(x.r)}`).join(', ');
const md = `# J5 — Windows judge map against mimalloc on current main (\`bench\`: measurement only; nothing changes)

Generated by \`node scripts/j5_report.mjs\` from \`docs/perf/j5/win_raw.jsonl\` (written by \`node docs/perf/wg1/run.mjs <exe> docs/perf/j5/win_raw.jsonl 12 3\`);
summary: \`docs/perf/J5_WINDOWS_JUDGE_MAP_summary.csv\`. Do not edit by hand.

## 1. Question

J2 and J4 measured bulk, churn and multi-thread cells; they said nothing about the growth, wild, phase and large shapes of the WG-1 judge, where the
last map (\`WG1_WINDOWS_MAP_AFTER_AO1.md\`, main \`338875ab\`) had Sefer behind in all seven scenarios. After NL-9, NL-11 and the rest of the
misuse-checks wave, where does mimalloc stand on those seven?

## 2. Method and identity

- Entry point and judge: as in \`WG1_WINDOWS_MAP_AFTER_AO1.md\` (\`examples/g1_wild_judge.rs\`: a static \`SeferAlloc\` reached through \`#[inline(never)]\`
  \`GlobalAlloc\` shims at the \`__rust_alloc\` boundary, arms \`sefer\` and \`mi\` in one binary, one process per run); \`--release --features production\`.
- Source identity: main \`${sha[1]}\`, built clean; judge binary sha256 \`${bin[1]}\` (\`docs/perf/j5/ident.txt\`).
- ${SCEN.length} scenarios, scale 1, seed 1; ${blocks.length} blocks; per block and arm the minimum \`ns_per_op\` over ${rows[0].reps} back-to-back repeats; scenario order shuffled per
  block with a fixed seed; the arm order alternates by block (\`docs/perf/wg1/run.mjs\`, unchanged).
- Per block d = ln(sefer / mi); the cell is exp(mean d) with a two-sided 95 % t-interval (${blocks.length - 1} degrees of freedom, quantile ${t}). A cell is "mimalloc ahead" only when
  the whole interval is above 1, "sefer ahead" only when it is below 1, otherwise a tie.
- Host: Windows dev host (single host, shared machine); no A/A control run in this session, so the intervals describe block-to-block spread only.

## 3. Result

| scenario | sefer / mimalloc now | 95 % CI | verdict | WG-1 (main 338875ab) | WG-1 95 % CI | blocks x repeats |
|---|---:|---|---|---:|---|---|
${table}

- Mimalloc ahead in ${behind.length} of ${SCEN.length} scenarios${behind.length ? ' (' + behind.map((x) => x.sc).join(', ') + ')' : ''}; ties ${tied.length}; Sefer ahead ${ahead.length}.
- Largest ratios: ${worst}.

## 4. Verdict

${behind.length === 0 ? 'No judge scenario has mimalloc ahead on a whole interval.' : 'The scenarios listed above are real losses to mimalloc on the Windows judge window; each is a candidate for its own attribution task, and the G1 criterion is not met on them.'}
This report changes nothing; it replaces the WG-1 reading as the current map.
`;
writeFileSync(new URL('J5_WINDOWS_JUDGE_MAP.md', dir), md);
console.log(md.split('\n').filter((l) => l.startsWith('| ') || l.startsWith('- Mimalloc') || l.startsWith('- Largest')).join('\n'));
