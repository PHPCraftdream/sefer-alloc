// NL-9: derives the iai Ir table (production with misuse-checks vs the new default production) from
// docs/perf/_raw_nl9_iai_{on,off}.log, writes docs/perf/NL9_IAI_summary.csv and docs/perf/NL9_IAI_BASELINE_SECTION.md
// (the section appended to docs/perf/IAI_BASELINE.md). Asserts every printed percentage.
import { readFileSync, writeFileSync } from 'node:fs';
const perf = new URL('../docs/perf/', import.meta.url);
function assert(c, m) { if (!c) throw new Error(m); }
function parse(name) {
  const text = readFileSync(new URL(name, perf), 'utf8');
  const rows = new Map();
  const start = text.indexOf('  bench                                                 Ir');
  assert(start >= 0, `${name}: summary table not found`);
  for (const line of text.slice(start).split('\n').slice(2)) {
    const m = line.match(/^ {2}([a-z0-9_]+)\s+([\d,]+)\s+([\d,]+)\s+([\d,]+)\s+([\d,]+)\s+([\d,]+)\s+(\S+)\s*$/);
    if (!m) { if (rows.size) break; continue; }
    const n = (s) => Number(s.replace(/,/g, ''));
    rows.set(m[1], { ir: n(m[2]), l1: n(m[3]), l2: n(m[4]), ram: n(m[5]), cyc: n(m[6]), irop: m[7] });
  }
  return rows;
}
const on = parse('_raw_nl9_iai_on.log'), off = parse('_raw_nl9_iai_off.log');
assert(on.size >= 100 && on.size === off.size, `bench count on=${on.size} off=${off.size}`);
let csv = 'bench,ir_on,ir_off,ir_delta,ir_delta_pct,estcycles_on,estcycles_off,estcycles_delta_pct\n';
const changed = [];
const f2 = (x) => x.toFixed(2);
for (const [k, a] of on) {
  const b = off.get(k);
  assert(b, `bench ${k} missing in off`);
  const d = b.ir - a.ir, p = (b.ir / a.ir - 1) * 100, cp = (b.cyc / a.cyc - 1) * 100;
  csv += `${k},${a.ir},${b.ir},${d},${f2(p)},${a.cyc},${b.cyc},${f2(cp)}\n`;
  changed.push({ k, a, b, d, p, cp });
}
writeFileSync(new URL('NL9_IAI_summary.csv', perf), csv);
const lower = changed.filter((c) => c.d < 0).length, same = changed.filter((c) => c.d === 0).length, higher = changed.filter((c) => c.d > 0).length;
assert(lower + same + higher === on.size, 'partition');
const key = ['small_churn_16b', 'churn_256b', 'cold_alloc_free_256x16b', 'cold_alloc_free_256x64b', 'recycle_alloc_free_256x16b', 'recycle_alloc_free_256x64b', 'dealloc_free_only_16b', 'dealloc_own_thread_body_only_16b']
  .filter((k) => on.has(k));
const keyRows = key.map((k) => {
  const c = changed.find((x) => x.k === k);
  return `| ${k} | ${c.a.ir.toLocaleString('en-US')} | ${c.b.ir.toLocaleString('en-US')} | ${f2(c.p)} % (${c.d} of ${c.a.ir}) | ${f2(c.cp)} % |`;
});
const worst = [...changed].sort((x, y) => y.p - x.p)[0];
const best = [...changed].sort((x, y) => x.p - y.p)[0];
// The one rise is reproduced by a standalone probe (docs/perf/nl9/xfree_probe.rs): 4096 cross-thread frees.
const tot = (n) => Number(readFileSync(new URL(n, perf), 'utf8').match(/^([\d,]+) \(100\.0%\)  PROGRAM TOTALS/m)[1].replace(/,/g, ''));
const xon = tot('nl9/raw/xfree.on.txt'), xoff = tot('nl9/raw/xfree.off.txt');
assert(higher === 1 && worst.k === 'r19_prf01_joined_producer_same_word', 'the single rise is the producer window');
assert(xoff - xon === worst.b.ir - worst.a.ir, 'the standalone probe must reproduce the bench delta exactly');
const FREES = 4096;
const perOp = ((xoff - xon) / FREES).toFixed(1);
const md = `
## NL-9 (2026-11-04) — \`production\` without \`misuse-checks\` (\`perf(runtime)\`, default flip)

Generated by \`node scripts/nl9_iai_table.mjs\` from \`docs/perf/_raw_nl9_iai_on.log\` and \`docs/perf/_raw_nl9_iai_off.log\`
(per-bench summary: \`docs/perf/NL9_IAI_summary.csv\`). **This is the new reference for \`production\`.**

- **What changed:** \`production\` no longer includes \`misuse-checks\` (the checks that only reject a contract violation). The
  \`on\` arm below is the former default, \`--features "production bench-internals internals misuse-checks"\`; the \`off\` arm is
  \`npm run iai\`'s default, \`production bench-internals internals\`. One tree (PR #201 branch), one run per arm,
  \`iai-callgrind-runner 0.14.2\`, valgrind 3.22.0, WSL Ubuntu-24.04, rustc 1.98.1.
- **Counts:** ${on.size} benches; Ir lower in ${lower}, equal in ${same}, higher in ${higher}. Largest drop ${best.k} ${f2(best.p)} %
  (${best.a.ir} → ${best.b.ir}); largest rise ${worst.k} ${f2(worst.p)} % (${worst.a.ir} → ${worst.b.ir}).
- Marginal Ir/op against mimalloc, new default (from the \`off\` log): see the "Sefer/mimalloc marginal Ir/op ratio" table at the end of
  \`docs/perf/_raw_nl9_iai_off.log\`.

| bench | Ir on | Ir off | Ir off vs on | Estimated Cycles off vs on |
|---|---:|---:|---:|---:|
${keyRows.join('\n')}

**The one rise, \`${worst.k}\` (${f2(worst.p)} %, ${worst.b.ir - worst.a.ir} Ir), is real and deterministic:** a second full run of the \`off\`
arm gave the same ${worst.b.ir} Ir. The bench is the producer window of ${FREES} cross-thread frees; the standalone probe
\`docs/perf/nl9/xfree_probe.rs\` (callgrind, \`--toggle-collect='*producer*'\`, raw \`docs/perf/nl9/raw/xfree.{on,off}.txt\`)
reproduces the delta exactly (${xon} → ${xoff}, ${xoff - xon} Ir = ${perOp} Ir per foreign free). No check was removed on that path (the
producer-side class check in \`SidecarBitmap::publish\` stays, NL-11). **Cause (task NL-12, closed without a code change):** register
allocation of the caller's loop, not library code. The listing of the probe's \`producer\`
(\`docs/perf/nl9/raw/xfree_producer.{on,off}.s\`) shows that with the checks compiled out LLVM hoists three GOT-loaded table
addresses out of the loop (arm \`on\`: one) and runs out of callee-saved registers, so the call to \`publish_foreign\` is wrapped by
three spill stores and three reloads instead of one store, one reload and two register moves: ${perOp} more moves per free,
exactly the measured delta. The shape belongs to a tight loop of consecutive frees in the harness (loop-invariant hoisting does
not apply to a single \`dealloc\` call site in ordinary code) and moves with any change of the inlined body. The same cross-thread
frees inside the real allocator workloads fall (larson/mstress T=4 -6.8 % and -8.8 % Ir in \`NL9_DEFAULT_FLIP.md\`), so no library change
is warranted; the rise stays in the table as measured.
`;
writeFileSync(new URL("NL9_IAI_BASELINE_SECTION.md", perf), md); /* appended to IAI_BASELINE.md by hand, then removed */
console.log(md);
