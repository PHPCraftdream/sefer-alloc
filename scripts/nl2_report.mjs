// NL-2: derives docs/perf/NL2_LANE_BOUND_CEILING.md and its summary CSV from docs/perf/nl2/raw (written by
// docs/perf/nl2/nl2.sh); asserts every printed ratio and the threshold verdict.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../docs/perf/nl2/raw/', import.meta.url);
const rd = (n) => readFileSync(new URL(n, dir), 'utf8');
const med = (a) => [...a].sort((x, y) => x - y)[a.length >> 1];
function assert(c, m) { if (!c) throw new Error(m); }
const ARMS = ['base', 'proto'];
const CELLS = ['bulk16', 'bulk64', 'larson1', 'larson4', 'mstress1', 'mstress4'];
const TIMED = ['bulk16', 'bulk64', 'larson1', 'larson4', 'mstress1', 'mstress4'];
const ORDER = { base: [1, 4], proto: [2, 3] };
const IR_THRESHOLD = 2.0, TIME_THRESHOLD = 1.5; // percent: the opt-in rule of the wave
const f2 = (x) => x.toFixed(2);
const ir = (arm, k) => Number(rd(`ir.${arm}.${k}.txt`).match(/^(\d+)/)[1]);
const out = {};
for (const k of CELLS) {
  const r = { base: {}, proto: {} };
  for (const arm of ARMS) {
    r[arm].ir = ir(arm, k);
    const t = [];
    for (let rep = 1; rep <= 5; rep++) for (const i of ORDER[arm]) {
      const o = rd(`run.${arm}.${k}.${rep}.${i}.stdout`);
      if (k.startsWith('bulk')) { const w = o.trim().split(/\s+/); assert(w[0] === 'bulk', 'bulk shape'); t.push(Number(w[5])); }
      else { const m = o.match(/T=(\d+) ([\d.]+) Mops/); assert(m && k.endsWith(m[1]), 'mops shape'); t.push(Number(m[2])); }
    }
    assert(t.length === 10, '10 samples');
    r[arm].t = med(t); r[arm].lo = Math.min(...t); r[arm].hi = Math.max(...t);
  }
  const unit = k.startsWith('bulk') ? 'ns/op' : 'Mops';
  const irp = (r.proto.ir / r.base.ir - 1) * 100;
  const tp = unit === 'Mops' ? (r.base.t / r.proto.t - 1) * 100 : (r.proto.t / r.base.t - 1) * 100;
  const overlap = Math.min(r.proto.lo, r.base.lo) <= Math.max(r.proto.lo, r.base.lo) && r.proto.lo <= r.base.hi && r.base.lo <= r.proto.hi;
  out[k] = { ...r, unit, irp, tp, overlap };
}
const maxIr = Math.max(...CELLS.map((k) => -out[k].irp));
const timeClaims = CELLS.filter((k) => Math.abs(out[k].tp) >= TIME_THRESHOLD && !out[k].overlap);
const verdict = maxIr >= IR_THRESHOLD || timeClaims.length ? 'GO' : 'NULL';
assert(verdict === 'NULL' || maxIr >= IR_THRESHOLD || timeClaims.length, 'verdict follows the thresholds');
let csv = 'cell,ir_base,ir_proto,ir_delta_pct,median_base,median_proto,unit,time_delta_pct,ranges_overlap\n';
const rows = CELLS.map((k) => {
  const o = out[k];
  csv += `${k},${o.base.ir},${o.proto.ir},${f2(o.irp)},${o.base.t},${o.proto.t},${o.unit},${f2(o.tp)},${o.overlap}\n`;
  return `| ${k} | ${o.base.ir} | ${o.proto.ir} | ${f2(o.irp)} % (${o.proto.ir - o.base.ir} of ${o.base.ir}) | ${o.base.t} [${o.base.lo}..${o.base.hi}] | ${o.proto.t} [${o.proto.lo}..${o.proto.hi}] | ${o.unit} | ${f2(o.tp)} % (${o.overlap ? 'ranges overlap' : 'ranges disjoint'}) |`;
});
writeFileSync(new URL('../../NL2_LANE_BOUND_CEILING_summary.csv', dir), csv);
const md = `# NL-2 — a cheaper bound in the free lane for builds that keep \`misuse-checks\` (\`bench\`: ceiling; verdict ${verdict})

Generated by \`node scripts/nl2_report.mjs\` from \`docs/perf/nl2/raw\` (written by \`docs/perf/nl2/nl2.sh\`); summary:
\`docs/perf/NL2_LANE_BOUND_CEILING_summary.csv\`. Do not edit by hand.

## 1. Question

In a build that keeps \`misuse-checks\` the free lane (\`dealloc_fast.rs\`, two sites) compares \`g >= bump >> 4\` before reading the state byte: a load of
\`bump\`, a shift and a compare per free. The state-byte compare that follows already rejects every granule at or past \`bump\` (those bytes are zero:
OS zero pages, and the decommit reset zeroes the carved range), so the guard only has to keep \`g\` inside the byte array and reject a misaligned offset
(\`g >= 2^60\`). A constant bound \`g >= FOOTPRINT\` does both without the load. Is it worth it?

## 2. Method and identity

- Entry point: \`b4_pmu_probe bulk sefer 1024 <16|64> <passes>\` and \`g1_mt_one <larson|mstress> sefer <T> <steps>\` on the real \`SeferAlloc\`
  \`#[global_allocator]\`, \`--features "production misuse-checks"\`, release, the repository's alignment RUSTFLAGS.
- Source identity: \`git archive\` of main \`36f21c03\`, tar sha256 in \`docs/perf/nl2/raw/identity.txt\`; the \`proto\` arm adds \`docs/perf/nl2/patches/nl2.patch\`.
- Instructions: callgrind (bulk 400 passes, MT 100000 steps). Time: 5 repetitions of base, proto, proto, base, 10 samples per arm and cell.
  Thresholds of the wave for an opt-in change: Ir >= ${IR_THRESHOLD} % or time >= ${TIME_THRESHOLD} % with disjoint ranges.

## 3. Result

| cell | Ir base | Ir proto | Ir proto vs base | median base [min..max] | median proto [min..max] | unit | time proto vs base |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

Time sign convention: negative = the proto arm does the work in less time.

## 4. Verdict

Largest Ir drop ${f2(maxIr)} % (threshold ${IR_THRESHOLD} %); cells with a time claim: ${timeClaims.length}. **${verdict}**: ${verdict === 'NULL' ? 'the cheaper bound is below the threshold in every cell, the time ranges overlap, and the change would also need the zero-byte invariant pinned by a new test. NL-2 is closed without a code change; the lane keeps its guard.' : 'see the table.'}
`;
writeFileSync(new URL('../../NL2_LANE_BOUND_CEILING.md', dir), md);
console.log(`maxIr ${f2(maxIr)} verdict ${verdict}`);
