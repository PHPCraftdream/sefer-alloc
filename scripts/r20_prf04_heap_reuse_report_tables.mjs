#!/usr/bin/env node
// Derives the PRF-04 heap-reuse gate report tables from one run directory
// (verdict.txt, summary.csv, input.json[.gz], environment.log). Every window
// delta is recomputed from summary.csv and asserted against the judge.
//
//   node scripts/r20_prf04_heap_reuse_report_tables.mjs <run-dir> > <run-dir>/report_tables.md
//   node scripts/r20_prf04_heap_reuse_report_tables.mjs <run-dir> --csv > docs/perf/<REPORT>_summary.csv
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const dir = process.argv[2];
const csvMode = process.argv[3] === '--csv';
assert.ok(dir, 'usage: r20_prf04_heap_reuse_report_tables.mjs <run-dir> [--csv]');
const read = name => fs.readFileSync(path.join(dir, name), 'utf8');
const readJson = name => JSON.parse(fs.existsSync(path.join(dir, name))
  ? read(name) : zlib.gunzipSync(fs.readFileSync(path.join(dir, `${name}.gz`))).toString('utf8'));

const vt = read('verdict.txt');
const verdict = JSON.parse(vt.slice(vt.indexOf('{')));
const input = readJson('input.json');
const env = read('environment.log').split('\n');
const host = env.find(l => l.startsWith('Linux '));
const valgrind = env.find(l => l.startsWith('valgrind-'));
const rustc = env.find(l => l.startsWith('rustc '));
assert.ok(host && valgrind && rustc, 'environment.log lacks host/valgrind/rustc');
assert.equal(input.ancestry.result, 'A ancestor B');
const [baseCommit, candidateCommit] = input.ancestry.chain;

const rows = new Map();
for (const line of read('summary.csv').trim().split('\n').slice(1)) {
  const [arm, name, ir] = line.split(',');
  rows.set(`${arm}/${name}`, BigInt(ir));
}
const ir = (arm, name) => {
  const v = rows.get(`${arm}/${name}`);
  assert.ok(v !== undefined, `summary.csv lacks ${arm}/${name}`);
  const r = input.iai.find(x => x.arm === arm && x.name === name);
  assert.equal(BigInt(r.Ir), v, `input.json disagrees for ${arm}/${name}`);
  return v;
};
const prefix = layer => (layer === 'L2' ? 'r20_prf04hr_l2_' : 'r20_prf04hr_');
const SIZES = ['n', '2n', '4n'];
const cellIr = (arm, layer, family, size) => (layer === 'L2' && family === 'recycled'
  ? ir(arm, `${prefix(layer)}recycled_alloc_${size}`) + ir(arm, `${prefix(layer)}recycled_release_${size}`)
  : ir(arm, `${prefix(layer)}${family}_${size}`));
const windowIr = (arm, layer, family, w) => cellIr(arm, layer, family, SIZES[w - 1]) -
  (w === 1 ? 0n : cellIr(arm, layer, family, SIZES[w - 2]));

const fmt = n => {
  const s = (n < 0n ? -n : n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  return n < 0n ? `−${s}` : s;
};
const signed = n => (n > 0n ? `+${fmt(n)}` : fmt(n));
const ratio = (num, den, places = 4) => {
  assert.ok(den > 0n);
  const neg = num < 0n;
  const scale = 10n ** BigInt(places);
  const q = ((neg ? -num : num) * scale * 2n + den) / (den * 2n);
  const s = q.toString().padStart(places + 1, '0');
  return `${neg ? '−' : ''}${s.slice(0, -places)}.${s.slice(-places)}`;
};

const out = [];
const line = s => out.push(s);
const records = [];
const rec = (check, a, b, valueA, valueB, denominator, limit, gating, pass) =>
  records.push([check, a, b, valueA, valueB, valueB - valueA, denominator ?? '', limit, gating, pass ? 'pass' : 'FAIL']);

line(`<!-- generated by scripts/r20_prf04_heap_reuse_report_tables.mjs from ${path.basename(dir)}; do not edit by hand -->`);
line('');
assert.notEqual(verdict.rehearsal, true);
line(`Verdict: **${verdict.verdict}**; flags ${JSON.stringify(verdict.flags)}.`);
line('');

line('### Benefit: thread waves (strict B < A)');
line('');
line('| Layer | Window | A1 | B1 | B1 − A1 | B1 / A1 | Judge |');
line('|---|---|---:|---:|---:|---:|---|');
for (const layer of ['L1', 'L2']) for (let w = 1; w <= 3; w++) {
  const a = windowIr('A1', layer, 'wave', w);
  const b = windowIr('B1', layer, 'wave', w);
  const c = verdict.tables.checks.find(x => x.cell === `${layer}/wave/w${w}` && x.pair === 'B1/A1');
  assert.equal(BigInt(c.delta), b - a);
  assert.equal(c.pass, b < a);
  rec(`${layer} wave w${w}`, 'A1', 'B1', a, b, a, 'B < A', true, c.pass);
  line(`| ${layer} | w${w} | ${fmt(a)} | ${fmt(b)} | ${signed(b - a)} | ${fmt(b)} / ${fmt(a)} = ${ratio(b, a)} | ${c.pass ? 'pass' : 'FAIL'} |`);
}
line('');

line('### Price windows (L2 gates: delta − T_s ≤ 1% of the A window; L1 is a diagnostic)');
line('');
line('| Layer | Family | Window | A1 window | B1 − A1 | Work | Per work | Share of A window | Gating | Judge |');
line('|---|---|---|---:|---:|---:|---:|---:|---|---|');
for (const w of verdict.tables.windows.filter(x => x.pair === 'B1/A1')) {
  const a = windowIr('A1', w.layer, w.family, w.window);
  const b = windowIr('B1', w.layer, w.family, w.window);
  assert.equal(BigInt(w.base), a);
  assert.equal(BigInt(w.delta), b - a);
  const work = BigInt(w.work);
  rec(`${w.layer} ${w.family} w${w.window}`, 'A1', 'B1', a, b, a, w.rule, w.gating, w.pass);
  line(`| ${w.layer} | ${w.family} | w${w.window} | ${fmt(a)} | ${signed(b - a)} | ${work} | ${ratio(b - a, work, 2)} | ${signed(b - a)} / ${fmt(a)} = ${ratio(100n * (b - a), a, 3)}% | ${w.gating ? 'yes' : 'no'} | ${w.pass ? 'pass' : 'FAIL'} |`);
}
line('');

line('### Linearity (gating: candidate delta; diagnostic: absolute arm)');
line('');
line('| Layer | Family | Kind | Pair / arm | Deviation | Bound | Gating | Judge |');
line('|---|---|---|---|---:|---:|---|---|');
for (const l of verdict.tables.linearity.filter(x => x.pair === 'B1/A1' || x.arm === 'A1')) {
  if (l.kind === 'delta') {
    const d = w => windowIr('B1', l.layer, l.family, w) - windowIr('A1', l.layer, l.family, w);
    const dev = d(3) - 2n * d(2);
    assert.equal(BigInt(l.deviation), dev < 0n ? -dev : dev);
  }
  rec(`${l.layer} ${l.family} linearity ${l.kind}`, l.pair ?? l.arm, '', 0n, BigInt(l.deviation), null, `<= ${l.bound}`, l.gating, l.pass);
  line(`| ${l.layer} | ${l.family} | ${l.kind} | ${l.pair ?? l.arm} | ${l.deviation} | ${l.bound} | ${l.gating ? 'yes' : 'no'} | ${l.pass ? 'pass' : 'FAIL'} |`);
}
line('');

const start = verdict.tables.checks.find(x => x.cell === 'r20_prf04hr_start' && x.pair === 'B1/A1');
const sa = ir('A1', 'r20_prf04hr_start');
const sb = ir('B1', 'r20_prf04hr_start');
assert.equal(BigInt(start.delta), sb - sa);
rec('start', 'A1', 'B1', sa, sb, sa, 'delta <= T_s + 4 and 5%', true, start.pass);
line(`Start cell \`r20_prf04hr_start\`: A1 ${fmt(sa)}, B1 ${fmt(sb)}, Δ ${signed(sb - sa)} — ${start.pass ? 'pass' : 'FAIL'}.`);
const noisy = verdict.tables.noise.filter(n => !n.pass).length;
line(`Noise rows: ${verdict.tables.noise.length}, failing ${noisy} (A1/A2/C0 absolute ceiling ${verdict.tables.noise[0]?.ceiling}).`);

if (csvMode) {
  const header = ['report', 'base_commit', 'candidate_commit', 'host', 'valgrind', 'rustc', 'check', 'arm_a', 'arm_b',
    'value_a', 'value_b', 'delta', 'denominator', 'limit', 'gating', 'verdict'];
  const fixed = [path.basename(dir) + '_REPORT', baseCommit, candidateCommit, host, valgrind, rustc.split(' (')[0]];
  const cell = v => (/[",]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
  process.stdout.write([header.join(','), ...records.map(r => [...fixed, ...r].map(cell).join(','))].join('\n') + '\n');
} else {
  process.stdout.write(out.join('\n') + '\n');
}
