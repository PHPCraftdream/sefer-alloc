// Markdown rendering for docs/perf/P1_5_SELECTION_POTENTIAL.md.
// Pure string assembly: every number is derived (no hand-typed figures), no
// clock, no random, no machine paths — two generations are byte-identical.

const pct = (num, den) => `${num} / ${den} = ${(100 * num / den).toFixed(2)}%`;
const secs = (n) => `${n} s`;

export function renderReport(d) {
  const L = [];
  L.push('# P1.5 selection potential (measurement input for G1)');
  L.push('');
  L.push('Generated by `scripts/ci-selection-history.mjs --report` (derived numbers only; none');
  L.push('typed by hand; deterministic: no clock, no randomness, no machine paths — two');
  L.push('consecutive generations are byte-identical). This report measures how much CI time');
  L.push('step P1.5 (selection by workspace crate graph) would have saved over the git history');
  L.push('window below, as INPUT 1 to decision G1 (`docs/perf/G1_DECISION_CRITERION.md`).');
  L.push('It makes NO GO/NO-GO decision; G1 decides against the criterion.');
  L.push('');
  L.push('## Window');
  L.push('');
  L.push(`- Commits analysed (N): ${d.window.n} first-parent MERGE commits of \`${d.window.ref}\`.`);
  L.push(`- Window base SHA (first parent of the OLDEST merge in the window): \`${d.window.baseSha}\`.`);
  L.push(`- Head SHA (\`${d.window.ref}\` tip at generation time): \`${d.window.headSha}\`.`);
  L.push(`- Per commit: files = \`git diff --name-only <p1> <sha>\` (p1 = first parent).`);
  L.push('');
  L.push('## Method (measurement model, verbatim)');
  L.push('');
  for (const line of d.method) L.push(line);
  L.push('');
  L.push('## Job weights (single representative run)');
  L.push('');
  L.push(`- Run: \`${d.weights.runId}\` (event \`${d.weights.event}\`, created ${d.weights.createdAt}), ${d.weights.jobCount} jobs.`);
  L.push(`- Mapped to workflow jobs by name: ${d.weights.mapped}; unmapped (synthetic bucket, excluded from both sides): ${d.weights.unmapped.length}${d.weights.unmapped.length ? ' — ' + d.weights.unmapped.map(n => `\`${n}\``).join(', ') : ''}.`);
  L.push(`- weekly/dispatch jobs excluded from both sides: ${d.weights.excluded}.`);
  L.push(`- skipped jobs (contribute 0, counted): ${d.weights.skipped}.`);
  L.push(`- jobs with null timestamps (contribute 0): ${d.weights.zeroTimestamp}.`);
  L.push('');
  L.push('## Aggregates');
  L.push('');
  for (const [label, agg] of [['PR policy (event pull_request; seam/os included)', d.agg.pull_request], ['push policy (event push; seam/os dropped)', d.agg.push]]) {
    L.push(`### ${label}`);
    L.push('');
    L.push(`- Eligible commits (denominator for the commit share): ${agg.eligibleCount}.`);
    L.push(`- Window CI seconds today (sum over eligible commits of selected-job seconds, \`always\` excluded): ${secs(agg.todaySeconds)}.`);
    L.push(`- Window CI seconds under the P1.5 model: ${secs(agg.p15Seconds)}.`);
    L.push(`- Delta seconds (today − P1.5): ${secs(agg.deltaSeconds)}.`);
    L.push(`- Share of eligible commits with delta > 0 (numerator: commits with delta > 0; denominator: eligible commits): ${pct(agg.commitsWithDelta, agg.eligibleCount)}.`);
    L.push(`- Share of window CI seconds saved (numerator: delta seconds; denominator: window CI seconds today): ${agg.todaySeconds ? pct(agg.deltaSeconds, agg.todaySeconds) : `0 / 0 (no window CI seconds today; share defined as 0)`}.`);
    L.push('');
  }
  L.push('### Per-affected-crate breakdown (both policies shown as PR / push)');
  L.push('');
  L.push('| crate | commits touched | seconds saved PR | seconds saved push |');
  L.push('| --- | --- | --- | --- |');
  const pushMap = new Map(d.agg.push.perCrate);
  for (const [crate, e] of d.agg.pull_request.perCrate) {
    const p = pushMap.get(crate) ?? { commits: 0, saved: 0 };
    L.push(`| ${crate} | ${e.commits} | ${e.saved} | ${p.saved} |`);
  }
  if (d.agg.pull_request.perCrate.length === 0) L.push('| (none) | 0 | 0 | 0 |');
  L.push('');
  L.push('## Non-eligible commits (savings 0, model undefined)');
  L.push('');
  for (const [bucket, b] of [...d.buckets.entries()].sort((a, b2) => a[0].localeCompare(b2[0]))) {
    L.push(`- \`${bucket}\`: ${b.count} commit(s) — e.g. ${b.shas.slice(0, 3).map(s => `\`${s.slice(0, 12)}\``).join(', ')}${b.sample.length ? '; sample path(s): ' + b.sample.map(s => `\`${s}\``).join(', ') : ''}.`);
  }
  if (d.buckets.size === 0) L.push('- none: every commit in the window is P1.5-eligible.');
  L.push('');
  L.push('## Per-commit table (eligible commits only)');
  L.push('');
  L.push('Groups are the cargo groups selected per policy (`always` excluded from both sides).');
  L.push('');
  L.push('| commit | changed crates | manifest | today PR groups | P1.5 PR groups | s today PR | s P1.5 PR | s today push | s P1.5 push |');
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const r of d.rows.filter(r => r.eligible)) {
    const pr = r.policies.pull_request, pu = r.policies.push;
    const gs = (s) => [...s].sort().join(',') || '(none)';
    L.push(`| \`${r.sha.slice(0, 12)}\` | ${r.changed.join(', ') || '(docs-only)'} | ${r.manifestTouch ? 'yes' : 'no'} | ${gs(pr.current)} | ${gs(pr.p15)} | ${pr.currentSeconds} | ${pr.p15Seconds} | ${pu.currentSeconds} | ${pu.p15Seconds} |`);
  }
  L.push('');
  L.push('## Flags raised by the model (conservative paths)');
  L.push('');
  const flags = new Map();
  for (const r of d.rows) for (const f of r.flags) flags.set(f, (flags.get(f) ?? 0) + 1);
  if (flags.size === 0) L.push('- none.');
  for (const [f, n] of [...flags.entries()].sort((a, b) => a[0].localeCompare(b[0]))) L.push(`- ${f} (${n} commit(s)).`);
  L.push('');
  L.push('## Honest limitations');
  L.push('');
  L.push('- Single representative run\'s job durations are applied to every commit; per-commit actual durations are not used.');
  L.push('- Push runs on main skip seam/os while PR runs include them — BOTH columns are shown and the policy choice is left to the reader.');
  L.push('- The P1.5 model is an upper-bound ceiling estimate: it assumes perfect per-crate selection and ignores that a real implementation still needs SOME root job for a dependent change.');
  L.push('- Manifest-touching commits (`crates/**/Cargo.toml`) are approximated by the crate-graph model; dev-dependency crates and cfg(loom/kani)-dependency crates use conservative fallbacks (see Flags above).');
  L.push('- The `always` group is excluded from BOTH sides of the comparison (it runs regardless).');
  L.push('- Job durations do not capture queue/wait time.');
  L.push('');
  L.push('This report makes NO GO/NO-GO decision. The decision is G1\'s, against');
  L.push('`docs/perf/G1_DECISION_CRITERION.md` (Input 1).');
  return L.join('\n') + '\n';
}

export const METHOD_RULES = [
  '- Current selection: per commit, groups exactly like `scripts/ci-plan.mjs --replay`:',
  '  `plan({files, event, trailerFull:false, seamTests, cargoBenchOnly})`, where `seamTests` is',
  '  the word-set helper ci-plan builds from `scripts/loom.mjs`/`scripts/miri.mjs`/',
  '  `scripts/miri-matrix.mjs` (reimplemented locally; not exported there), and `cargoBenchOnly`',
  '  is `cargoTomlBenchOnly` of `git diff -U0 <p1> <sha> -- Cargo.toml` when files include `Cargo.toml`.',
  '  TWO policies are reported as two columns: PR policy (event `pull_request`) and push policy',
  '  (event `push`, which drops seam/os).',
  '- P1.5-eligible commits: diff paths ALL inside `crates/**`, `docs/**`, or `*.md`. Commits',
  '  touching anything else are NOT eligible: model undefined, savings 0, counted in a separate',
  '  bucket. Within eligible commits, a flag marks commits touching a `crates/**/Cargo.toml`',
  '  (manifest change — the crate-graph model approximates these).',
  '- P1.5 selection for an eligible commit: changed crates = distinct workspace crate dirs',
  '  matched by `^crates/[^/]+/([^/]+)/` (the crate NAME; the historical flat',
  '  `crates/<crate>/...` shape resolves through the same member-dir set); affected set =',
  '  changed crates ∪ transitive workspace CONSUMERS (consumer→dependency edges parsed',
  '  cargo-free from each member manifest\'s `[dependencies]`: a member name key with `path = "..."`;',
  '  optional consumers included, flagged). Then:',
  '  (a) for each affected workspace crate X with a `CRATE_GROUPS` entry: group `CRATE_GROUPS[X]`;',
  '  (b) if the ROOT crate `sefer-alloc` is an affected consumer: add exactly those ROOT job',
  '      groups (fast, seam, os) whose jobs build X — derived from ci.yml text: jobs via',
  '      `parseJobs`, then each root job block\'s `run:` lines scanned for `--features <tokens>`',
  '      and `--all-features`; feature tokens mapped to optional root deps via the root manifest',
  '      `[features]` closure (`dep:X` entries); `--all-features` builds every optional dep; a',
  '      MANDATORY normal dep is built by ALL root groups; deps under',
  '      `[target.\'cfg(any(loom, kani))\'.dependencies]` and all `[dev-dependencies]` are NOT',
  '      derivable from run lines → conservatively add ALL root groups and FLAG it (Flags section);',
  '  (c) the `always` group is excluded from BOTH sides of the comparison (runs regardless).',
  '- A changed crate with no `CRATE_GROUPS` entry falls back to today\'s selection for that',
  '  commit\'s crate paths, flagged.',
  '- Weights: seconds of each job in the selected groups = `completed_at − started_at` from the',
  '  full-run JSON (null timestamps contribute 0; skipped jobs contribute 0 and are counted).',
  '  Job→group mapping via `parseJobs` on the effective ci.yml matched by job NAME; a run job',
  '  matching no workflow job is counted under a synthetic "unmapped" bucket and reported. A job',
  '  selected by several groups counts ONCE (union of groups). weekly/dispatch jobs are excluded',
  '  from both sides.',
];
