// Writes docs/verification/GHOST_INVENTORY.md and its _summary.csv from a green inventory run of
// scripts/ghost_inventory.mjs (`--report <md>`). Every number is computed here from the site list and
// asserted against the counts the inventory already checked; nothing is typed by hand.
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT } from './lib.mjs';

const code = (s) => '`' + s + '`';
const cell = (s) => String(s).replace(/\|/g, '\\|');

export function writeReport(mdPath, r) {
  const { catalog, sites, byClass, claimed, gaps, doubles, dead, pv, nFiles, perScope } = r;
  assert.equal(gaps.length + doubles.length + dead.length + pv.errors.length, 0, 'report only from a green inventory');
  assert.equal(claimed, sites.length, 'every site claimed');
  const byProto = new Map(catalog.protocols.map((p) => [p.id, sites.filter((x) => x.protocol === p.id)]));
  for (const p of catalog.protocols) assert.equal(byProto.get(p.id).length, pv.sitesOf.get(p.id), `${p.id} site count`);
  const classSum = Object.values(byClass).reduce((a, b) => a + b, 0);
  assert.equal(classSum, sites.length, 'class shares sum to all sites');
  const shadow = catalog.protocols.filter((p) => /S/.test(p.class));
  const noModel = catalog.protocols.filter((p) => p.loom.length === 0 && p.class !== 'T');
  const L = [];
  L.push('# Ghost-checks G0 inventory (generated)', '');
  L.push(`Generated by ${code('node scripts/ghost_inventory.mjs --check --report docs/verification/GHOST_INVENTORY.md')}`);
  L.push(`from ${code('docs/verification/ghost-rules.json')} and the source tree; do not edit by hand.`);
  L.push(`Plan: ${code('docs/GHOST_CHECKS_PLAN.md')} §2, §8 G0. The scanner is text-based (comments and literals`);
  L.push(`blanked, braces give the item path); G1's ${code('crates/ghost-lint')} on ${code('syn')} replaces it as the authority.`, '');
  L.push('## 1. Ordering sites', '');
  L.push(`${sites.length} calls that carry a memory ordering (atomic methods, fences, and wrappers such as`);
  L.push(`${code('HeapSlot::cas_state')} whose arguments name an ordering) in ${nFiles} files of ${code('src/**')} and`);
  L.push(`${code('crates/*/src/**')}; each is claimed by exactly one of ${catalog.scopes.length} scopes.`, '');
  L.push('| class | sites | of all sites |', '|---|---:|---:|');
  for (const [k, v] of Object.entries(byClass).sort()) L.push(`| ${k} | ${v} | ${v}/${sites.length} |`);
  L.push(`| **claimed** | **${claimed}** | ${claimed}/${sites.length} |`);
  L.push(`| unclaimed | ${gaps.length} | ${gaps.length}/${sites.length} |`);
  L.push(`| claimed twice | ${doubles.length} | ${doubles.length}/${sites.length} |`, '');
  L.push('Classes: `protocol` — the ordering is part of a cross-thread protocol (P-id in §2); `lock-local` —');
  L.push('Relaxed under a lock, an owned pin or `&mut`; `counter` — statistics nobody synchronises on;');
  L.push('`test-hook` — `dbg_*`/`*_for_test` functions and fault-injection flags; `id` — unique-id generators;');
  L.push('`cache` — idempotent caches of a process constant; `twin` — `cfg(loom)` stand-ins; `kani` — proof');
  L.push('harness; `non-atomic` — named scanner false positives.', '');
  L.push('## 2. Protocols', '');
  L.push('| id | protocol | class | sites | loom tests | text pins | registry rows | real code under loom | decision | phase |');
  L.push('|---|---|---|---:|---:|---:|---|---|---|---|');
  for (const p of catalog.protocols) {
    L.push(`| ${p.id} | ${cell(p.name)} | ${p.class} | ${byProto.get(p.id).length} | ${p.loom.length} | ${p.pins.length} | ${p.registry.join(' ') || '—'} | ${cell(p.real_under_loom)} | ${cell(p.decision)} | ${p.phase} |`);
  }
  L.push('');
  L.push(`Shadow-model protocols (class contains S): ${shadow.length} of ${catalog.protocols.length}, each with a decision.`);
  L.push(`Protocols with neither a loom nor a shadow model: ${noModel.map((p) => p.id).join(', ') || 'none'} (${noModel.length} of ${catalog.protocols.length}).`, '');
  L.push('## 3. Invariants and prod places', '');
  for (const p of catalog.protocols) {
    L.push(`### ${p.id} — ${p.name}`, '');
    if (p.prod.length) L.push('Prod: ' + p.prod.map(code).join(', ') + '.', '');
    for (const i of p.invariants) L.push('- ' + i);
    if (p.atomics) L.push('- no atomic sites of its own: ' + p.atomics);
    if (p.loom.length) L.push('- loom: ' + p.loom.map(code).join(', '));
    L.push('', `Decision: **${p.decision}** — ${p.reason}`, '');
  }
  L.push('## 4. Scopes', '', '| scope | class | protocol | sites | reason |', '|---|---|---|---:|---|');
  for (const sc of catalog.scopes) L.push(`| ${code(sc.id)} | ${sc.class} | ${sc.protocol || '—'} | ${perScope.get(sc.id)} | ${cell(sc.reason)} |`);
  L.push('');
  writeFileSync(join(REPO_ROOT, mdPath), L.join('\n'));
  const csv = ['metric,value', `ordering_sites,${sites.length}`, `files,${nFiles}`, `scopes,${catalog.scopes.length}`,
    `protocols,${catalog.protocols.length}`, `unclaimed,${gaps.length}`, `claimed_twice,${doubles.length}`,
    `dead_scopes,${dead.length}`, `protocol_errors,${pv.errors.length}`, `prod_paths_checked,${pv.paths}`,
    `shadow_protocols,${shadow.length}`, `protocols_without_model,${noModel.length}`];
  for (const [k, v] of Object.entries(byClass).sort()) csv.push(`class_${k},${v}`);
  for (const p of catalog.protocols) csv.push(`sites_${p.id},${byProto.get(p.id).length}`);
  writeFileSync(join(REPO_ROOT, mdPath.replace(/\.md$/, '_summary.csv')), csv.join('\n') + '\n');
}
