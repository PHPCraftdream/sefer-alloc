// J6: derives docs/perf/J6_LINUX_JUDGE_MAP.md and docs/perf/J6_LINUX_JUDGE_MAP_summary.csv from docs/perf/j6/linux_raw.jsonl
// (written by `node docs/perf/j6/run.mjs <linux exe> docs/perf/j6/linux_raw.jsonl 12 3`), next to the Windows reading of J5
// (docs/perf/J5_WINDOWS_JUDGE_MAP_summary.csv). Same statistic as J5: per block and arm the minimum ns/op over the repeats,
// d = ln(sefer / mi), cell = exp(mean d) with a two-sided 95 % t-interval. Asserts every printed number.
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const dir = new URL('../docs/perf/', import.meta.url);
const rd = (p) => readFileSync(new URL(p, dir), 'utf8');
const T975 = { 3: 3.182, 5: 2.571, 7: 2.365, 9: 2.262, 11: 2.201, 15: 2.131 };
const SCEN = ['grow64', 'grow1k', 'regrow', 'growmix', 'wild', 'phase', 'large'];
const recs = rd('j6/linux_raw.jsonl').trim().split(/\r?\n/).map((l) => JSON.parse(l));
const ident = rd('j6/ident.txt');
const tar = /^tar ([0-9a-f]{64})$/m.exec(ident), bin = /^bin ([0-9a-f]{64})$/m.exec(ident), src = /^main ([0-9a-f]{40})$/m.exec(ident);
assert.ok(tar && bin && src, 'identity lines');
const cpu = /model name\s*:\s*(.*)$/m.exec(ident)?.[1] ?? 'unknown', cpus = /logical cpus: (\d+)/.exec(ident)?.[1] ?? '?';
const win = {};
for (const l of rd('J5_WINDOWS_JUDGE_MAP_summary.csv').trim().split(/\r?\n/).slice(1)) {
  const c = l.split(',');
  win[c[0]] = { r: +c[1], lo: +c[2], hi: +c[3] };
}
const blocks = [...new Set(recs.map((r) => r.block))].sort((a, b) => a - b);
const t = T975[blocks.length - 1];
assert.ok(t, `no t quantile for n=${blocks.length}`);
assert.deepEqual([...new Set(recs.map((r) => r.r.scenario))].sort(), [...SCEN].sort());
const f3 = (x) => x.toFixed(3);
const rows = [];
let csv = 'scenario,sefer_over_mi,ci_lo,ci_hi,verdict,win_sefer_over_mi,win_lo,win_hi,blocks,repeats\n';
for (const sc of SCEN) {
  const d = blocks.map((b) => {
    const mn = (arm) => {
      const v = recs.filter((r) => r.block === b && r.arm === arm && r.r.scenario === sc).map((r) => r.r.ns_per_op);
      assert.ok(v.length >= 1, `samples ${b} ${arm} ${sc}`);
      return Math.min(...v);
    };
    return Math.log(mn('sefer') / mn('mi'));
  });
  const n = d.length, m = d.reduce((a, b) => a + b, 0) / n;
  const sd = Math.sqrt(d.reduce((a, b) => a + (b - m) ** 2, 0) / (n - 1));
  const half = t * sd / Math.sqrt(n);
  const [r, lo, hi] = [Math.exp(m), Math.exp(m - half), Math.exp(m + half)];
  assert.ok(lo <= r && r <= hi, 'interval contains the estimate');
  const reps = recs.filter((x) => x.block === blocks[0] && x.arm === 'sefer' && x.r.scenario === sc).length;
  assert.ok(win[sc], `J5 row for ${sc}`);
  const verdict = hi < 1 ? 'sefer ahead' : lo > 1 ? 'mimalloc ahead' : 'tie (interval contains 1)';
  rows.push({ sc, r, lo, hi, verdict, n, reps });
  csv += `${sc},${f3(r)},${f3(lo)},${f3(hi)},${verdict},${f3(win[sc].r)},${f3(win[sc].lo)},${f3(win[sc].hi)},${n},${reps}\n`;
}
writeFileSync(new URL('J6_LINUX_JUDGE_MAP_summary.csv', dir), csv);
const behind = rows.filter((x) => x.verdict === 'mimalloc ahead');
const ahead = rows.filter((x) => x.verdict === 'sefer ahead');
const tied = rows.filter((x) => x.verdict.startsWith('tie'));
assert.equal(behind.length + ahead.length + tied.length, SCEN.length);
const table = rows.map((x) => `| ${x.sc} | ${f3(x.r)} | ${f3(x.lo)}–${f3(x.hi)} | ${x.verdict} | ${f3(win[x.sc].r)} | ${f3(win[x.sc].lo)}–${f3(win[x.sc].hi)} | ${x.n} x ${x.reps} |`).join('\n');
const worst = [...rows].sort((a, b) => b.r - a.r).slice(0, 3).map((x) => `${x.sc} ${f3(x.r)}`).join(', ');
const common = rows.filter((x) => x.verdict === 'mimalloc ahead' && win[x.sc].lo > 1).map((x) => x.sc);
const md = `# J6 — Linux (WSL2) judge map against mimalloc on current main (\`bench\`: measurement only; nothing changes)

Generated by \`node scripts/j6_report.mjs\` from \`docs/perf/j6/linux_raw.jsonl\` (written by \`node docs/perf/j6/run.mjs <linux exe> docs/perf/j6/linux_raw.jsonl 12 3\`);
summary: \`docs/perf/J6_LINUX_JUDGE_MAP_summary.csv\`. Do not edit by hand.

## 1. Question

J5 found mimalloc ahead in 6 of 7 judge scenarios on Windows. Is the gap specific to the Windows memory interface (VirtualAlloc, commit, decommit),
or does it show on Linux too, where \`perf\` and callgrind can attribute it?

## 2. Method and identity

- Same judge, same campaign as J5 (\`examples/g1_wild_judge.rs\`, scale 1, seed 1, ${blocks.length} blocks, ${rows[0].reps} repeats, the shuffle seed and arm alternation of \`docs/perf/wg1/run.mjs\`);
  the Linux binary is started through \`wsl.exe -e\` by \`docs/perf/j6/run.mjs\`; ns/op is measured inside the judge, so the launcher is outside every sample.
- Source identity: main \`${src[1]}\`, git-archive tar sha256 \`${tar[1]}\`, judge binary sha256 \`${bin[1]}\` (\`docs/perf/j6/ident.txt\`, \`docs/perf/j6/build.sh\`).
  Build: \`--release --features production\` with the repository's alignment RUSTFLAGS (J5's Windows build used none).
- Host: WSL2 on the shared Windows dev host, ${cpus} logical CPUs, ${cpu}. Not bare-metal Linux: the memory interface is the WSL2 kernel's.
- Statistic as in J5: per block d = ln(sefer / mi), cell = exp(mean d), 95 % t-interval (${blocks.length - 1} degrees of freedom, quantile ${t}); "ahead" only when the whole interval is on one side of 1.

## 3. Result

| scenario | sefer / mimalloc (Linux) | 95 % CI | verdict | J5 Windows | J5 95 % CI | blocks x repeats |
|---|---:|---|---|---:|---|---|
${table}

- Mimalloc ahead in ${behind.length} of ${SCEN.length} scenarios${behind.length ? ' (' + behind.map((x) => x.sc).join(', ') + ')' : ''}; ties ${tied.length}; Sefer ahead ${ahead.length}.
- Largest ratios: ${worst}.
- Scenarios where mimalloc is ahead on BOTH platforms: ${common.length ? common.join(', ') : 'none'}.

## 4. Verdict

${behind.length === 0 ? 'No judge scenario has mimalloc ahead on Linux: the J5 gaps are specific to the Windows memory interface.' : common.length ? 'The scenarios common to both platforms are not a Windows artefact; they are the ones to attribute with perf and callgrind (J7).' : 'The Linux losses and the Windows losses are different scenarios; each platform needs its own attribution.'}
This report changes nothing.
`;
writeFileSync(new URL('J6_LINUX_JUDGE_MAP.md', dir), md);
console.log(md.split('\n').filter((l) => l.startsWith('| ') || l.startsWith('- Mimalloc') || l.startsWith('- Largest') || l.startsWith('- Scenarios')).join('\n'));
