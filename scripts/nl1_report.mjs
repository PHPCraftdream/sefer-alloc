// NL-1: derives docs/perf/NL1_MISUSE_CHECKS_OFF_summary.csv and prints the report tables from
// docs/perf/nl1/raw (written by docs/perf/nl1/nl1.sh); asserts every printed ratio.
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../docs/perf/nl1/raw/', import.meta.url);
const rd = (n) => readFileSync(new URL(n, dir), 'utf8');
const med = (a) => [...a].sort((x, y) => x - y)[a.length >> 1];
function assert(c, m) { if (!c) throw new Error(m); }
const ARMS = ['on', 'off'];
const BULK = ['bulk16', 'bulk64'];
const MT = ['larson1', 'larson4', 'mstress1', 'mstress4'];
const REPS = [1, 2, 3, 4, 5];
const POS = [1, 2, 3, 4];
const ORDER = { on: [1, 4], off: [2, 3] }; // ABBA positions per arm
const cells = [];
for (const k of [...BULK, ...MT]) {
  for (const arm of ARMS) {
    const ir = Number(rd(`ir.${arm}.${k}.txt`).match(/^(\d+)/)[1]);
    const t = [], cy = [];
    for (const r of REPS) {
      for (const i of ORDER[arm]) {
        const out = rd(`run.${arm}.${k}.${r}.${i}.stdout`);
        if (BULK.includes(k)) {
          const o = out.trim().split(/\s+/);
          assert(o[0] === 'bulk' && o[1] === 'sefer', `stdout shape ${arm} ${k}`);
          t.push(Number(o[5]));
          for (const l of rd(`stat.${arm}.${k}.${r}.${i}.txt`).split('\n')) {
            const f = l.split(',');
            if (f[2] === 'cycles:u') cy.push(Number(f[0]));
          }
        } else {
          const m = out.match(/T=(\d+) ([\d.]+) Mops/);
          assert(m && k.endsWith(m[1]), `mops shape ${arm} ${k}`);
          t.push(Number(m[2]));
        }
      }
    }
    assert(t.length === 10, `10 samples ${arm} ${k}`);
    if (BULK.includes(k)) assert(cy.length === 10, `10 cycle samples ${arm} ${k}`);
    cells.push({ k, arm, ir, time: med(t), unit: BULK.includes(k) ? 'ns/op' : 'Mops', cy: BULK.includes(k) ? med(cy) : null, samples: t });
  }
}
const get = (k, arm) => cells.find((c) => c.k === k && c.arm === arm);
let csv = 'cell,arm,callgrind_ir,ir_vs_on_pct,median_time,time_unit,time_vs_on_pct,median_cycles_u,cycles_vs_on_pct,time_min,time_max\n';
for (const c of cells) {
  const b = get(c.k, 'on');
  const irp = (c.ir / b.ir - 1) * 100;
  // ns/op: lower is better; Mops: higher is better. time_vs_on is the change in work time.
  const tp = c.unit === 'Mops' ? (b.time / c.time - 1) * 100 : (c.time / b.time - 1) * 100;
  const cyp = c.cy === null ? '' : ((c.cy / b.cy - 1) * 100).toFixed(2);
  const lo = Math.min(...c.samples), hi = Math.max(...c.samples);
  csv += `${c.k},${c.arm},${c.ir},${irp.toFixed(2)},${c.time},${c.unit},${tp.toFixed(2)},${c.cy ?? ''},${cyp},${lo},${hi}\n`;
  console.log(`| ${c.k} | ${c.arm} | ${c.ir} | ${irp.toFixed(2)} % | ${c.time} ${c.unit} [${lo}..${hi}] | ${tp.toFixed(2)} % |`);
}
writeFileSync(new URL('../../NL1_MISUSE_CHECKS_OFF_summary.csv', dir), csv);
// the off arm only removes work: it must not execute more instructions than the on arm in any cell.
for (const k of [...BULK, ...MT]) assert(get(k, 'off').ir <= get(k, 'on').ir, `off <= on at ${k}`);

// ---- the report, with every number taken from the cells above ----
const f2 = (x) => x.toFixed(2);
const pct = (k, arm) => {
  const c = get(k, arm), b = get(k, 'on');
  return { ir: (c.ir / b.ir - 1) * 100, t: c.unit === 'Mops' ? (b.time / c.time - 1) * 100 : (c.time / b.time - 1) * 100 };
};
const rows = [...BULK, ...MT].map((k) => {
  const on = get(k, 'on'), off = get(k, 'off'), p = pct(k, 'off');
  const noisy = /^(larson|mstress)4$/.test(k);
  return `| ${k} | ${on.ir} | ${off.ir} | ${f2(p.ir)} % (${off.ir - on.ir} of ${on.ir}) | ${on.time} [${Math.min(...on.samples)}..${Math.max(...on.samples)}] | ${off.time} [${Math.min(...off.samples)}..${Math.max(...off.samples)}] | ${on.unit} | ${noisy ? 'no claim (T=4, ranges overlap)' : f2(p.t) + ' % (' + off.time + ' vs ' + on.time + ' ' + on.unit + ', 10 samples per arm)'} |`;
});
// the ranges of the T=4 cells must overlap, otherwise the "no claim" label would hide a real difference
for (const k of MT.filter((x) => x.endsWith('4'))) {
  const a = get(k, 'on').samples, b = get(k, 'off').samples;
  assert(Math.min(...b) <= Math.max(...a) && Math.min(...a) <= Math.max(...b), `T=4 ranges overlap ${k}`);
}
