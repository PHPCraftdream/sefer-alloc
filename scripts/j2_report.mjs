// J2: derives docs/perf/J2_PAIRED_TABLE_POST_NL11.md from docs/perf/j2/paired.out (written by
// `node scripts/bench-table-paired.mjs`) and the two criterion runs docs/perf/_raw_nl9_bench_table{,_run2}.log;
// asserts the claims it prints.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../docs/perf/', import.meta.url);
const rd = (n) => readFileSync(new URL(n, root), 'utf8');
function assert(c, m) { if (!c) throw new Error(m); }
const paired = rd('j2/paired.out');
const manifest = JSON.parse(rd('j2/paired.manifest.json'));
const SIZES = ['16B', '64B', '256B', '1024B'];
// paired: three groups, 4 rows each, "| 16B | s (lo–hi) | m (lo–hi) | sys (lo–hi) | **r× faster** |"
const rows = [];
for (const line of paired.split('\n')) {
  const m = line.match(/^\| (\d+B) \| ([\d.]+) \(([\d.]+)–([\d.]+)\) \| ([\d.]+) \(([\d.]+)–([\d.]+)\) \| ([\d.]+) \([\d.]+–[\d.]+\) \| (?:\*\*)?([\d.]+)× (faster|slower)/);
  if (m) rows.push({ size: m[1], s: +m[2], sLo: +m[3], sHi: +m[4], m: +m[5], mLo: +m[6], mHi: +m[7], ratio: +m[9], dir: m[10] });
}
assert(rows.length === 12, `12 paired rows, got ${rows.length}`);
const GROUPS = ['Warm bulk burst', 'Churn, non-writing', 'Churn + write'];
let table = '| group | size | SeferAlloc ns/pair (range) | mimalloc ns/pair (range) | Sefer vs mimalloc | ranges |\n|---|---|---:|---:|---:|---|\n';
let behind = 0, tied = 0;
rows.forEach((r, i) => {
  assert(r.size === SIZES[i % 4], `size order ${i}`);
  const calc = r.s <= r.m ? r.m / r.s : r.s / r.m;
  assert(Math.abs(calc - r.ratio) <= 0.06 * r.ratio, `ratio ${i}: ${calc} vs ${r.ratio}`);
  const disjoint = r.sHi < r.mLo || r.mHi < r.sLo;
  if (r.dir === 'slower') behind++;
  if (!disjoint) tied++;
  table += `| ${GROUPS[Math.floor(i / 4)]} | ${r.size} | ${r.s} (${r.sLo}–${r.sHi}) | ${r.m} (${r.mLo}–${r.mHi}) | ${r.ratio}× ${r.dir} | ${disjoint ? 'disjoint' : 'overlap'} |\n`;
});
assert(behind === 0, 'no cell where mimalloc leads');
const narrow = [...rows].sort((a, b) => a.ratio - b.ratio)[0];
// criterion teardown diagnostic, two runs
function teardown(file) {
  const t = rd(file);
  const i = t.indexOf('### Churn + teardown');
  assert(i >= 0, `${file}: teardown heading`);
  const out = {};
  for (const line of t.slice(i).split('\n').slice(1)) {
    const m = line.match(/^\| (\d+B) \| ([\d.]+) \| ([\d.]+) \| ([\d.]+) \| (?:\*\*)?([\d.]+)× (faster|slower)/);
    if (m) out[m[1]] = { s: +m[2], m: +m[3], ratio: +m[5], dir: m[6] };
    else if (Object.keys(out).length) break;
  }
  assert(Object.keys(out).length === 4, `${file}: four teardown rows`);
  return out;
}
const t1 = teardown('_raw_nl9_bench_table.log'), t2 = teardown('_raw_nl9_bench_table_run2.log');
assert(t1['1024B'].dir === 'slower' && t2['1024B'].dir === 'slower', 'the 1024 B teardown cell trails in both runs');
const tr = (k) => `| ${k} | ${t1[k].s} vs ${t1[k].m} (${t1[k].ratio}× ${t1[k].dir}) | ${t2[k].s} vs ${t2[k].m} (${t2[k].ratio}× ${t2[k].dir}) |`;
const md = `# J2 — paired table against mimalloc after the misuse-checks wave (\`bench\`: measurement only; nothing changes)

Generated by \`node scripts/j2_report.mjs\` from \`docs/perf/j2/paired.out\` (written by \`node scripts/bench-table-paired.mjs --processes 3 --rounds 200\`)
and the two criterion runs \`docs/perf/_raw_nl9_bench_table.log\`, \`..._run2.log\`. Do not edit by hand.

## 1. Question

After NL-9 and NL-11 (main \`${manifest.commit.slice(0, 8)}\`), is there a cell where mimalloc is ahead?

## 2. Method and identity

- Entry point: \`examples/bench_table_paired.rs\` on the real \`SeferAlloc\`, \`mimalloc\` and \`System\` global allocators, features \`${manifest.features}\`, regime \`${manifest.regime}\`,
  ${manifest.processes} fresh processes x ${manifest.rounds} rounds; every round measures every arm once per cell, the arm order walks all six permutations.
  Cell = median over processes of the per-process minimum ns/pair, range of the per-process minimums in parentheses.
- Source identity: commit \`${manifest.commit}\` (manifest \`dirty: false\`; executable and raw-data sha256 in \`docs/perf/j2/paired.manifest.json\`); raw per-sample lines \`docs/perf/j2/paired.p{1,2,3}.jsonl.gz\`
  (\`node scripts/bench-table-paired.mjs --from docs/perf/j2/paired\` reprints the tables byte for byte).
- Host: Windows dev host, ${manifest.cpu}, ${manifest.rustc[0]}. Single host; the usual noise band applies, which is why the table reports ranges.

## 3. Result: paired single-thread cells

${table}
- Cells where mimalloc is ahead: ${behind} of 12. Cells whose Sefer and mimalloc ranges overlap (a tie): ${tied} of 12.
- Narrowest lead: ${narrow.ratio}x (${narrow.size}, ${narrow.s} vs ${narrow.m} ns/pair).

## 4. Residual loss: the teardown diagnostic

The criterion group \`Churn + teardown\` keeps segment decommit, release and re-reserve inside the timed region (a deliberate diagnostic,
\`bench_global_alloc_churn_with_teardown\`). Two full criterion runs on the same day (ns/pair, Sefer vs mimalloc):

| size | run 1 | run 2 |
|---|---|---|
${SIZES.map(tr).join('\n')}

The 1024 B cell trails in both runs (${t1['1024B'].ratio}x and ${t2['1024B'].ratio}x slower); every smaller size leads or ties. It is the only cell in any of the tables
where mimalloc is ahead, and it is the next candidate (cost of releasing and re-reserving segments that hold 1024 B blocks).

## 5. Verdict

No steady-state single-thread loss to mimalloc remains in these 12 cells. The open loss is the 1024 B teardown cell; it is filed as task J3.
`;
writeFileSync(new URL('J2_PAIRED_TABLE_POST_NL11.md', root), md);
console.log(md.split('\n').filter((l) => l.startsWith('- Cells') || l.startsWith('- Narrowest') || l.startsWith('| 1024B')).join('\n'));
