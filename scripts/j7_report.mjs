// J7 step 1: splits the J6 (Linux) and J5 (Windows) judge gaps into user time, kernel time and page faults from the per-run counters
// the judge already prints (docs/perf/j6/linux_raw.jsonl, docs/perf/j5/win_raw.jsonl). No new run. Per scenario and arm the median over
// the runs of ns_per_op, user_ms, kernel_ms, faults and peak/end RSS; the gap is sefer minus mimalloc, so user + kernel carry
// the whole CPU gap and the kernel share says how much of it is the memory interface (page faults, release, THP) and not allocator code.
// Writes docs/perf/J7_GAP_SPLIT.md and docs/perf/J7_GAP_SPLIT_summary.csv; asserts every printed number.
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { gunzipSync } from 'node:zlib';
const dir = new URL('../docs/perf/', import.meta.url);
const load = (p) => readFileSync(new URL(p, dir), 'utf8').trim().split(/\r?\n/).map((l) => JSON.parse(l));
const SCEN = ['grow64', 'grow1k', 'regrow', 'growmix', 'wild', 'phase', 'large'];
const med = (a) => { const s = [...a].sort((x, y) => x - y); const n = s.length; return n % 2 ? s[n >> 1] : (s[n / 2 - 1] + s[n / 2]) / 2; };
const f1 = (x) => x.toFixed(1);
const PLAT = [['Linux (WSL2), J6', 'j6/linux_raw.jsonl'], ['Windows, J5', 'j5/win_raw.jsonl']];
let csv = 'platform,scenario,arm,runs,ns_per_op,user_ms,kernel_ms,faults,peak_rss_mib,end_rss_mib\n';
let md = `# J7 step 1 — where the judge gap sits: user time, kernel time, page faults (\`bench\`: measurement only; nothing changes)

Generated by \`node scripts/j7_report.mjs\` from \`docs/perf/j6/linux_raw.jsonl\` and \`docs/perf/j5/win_raw.jsonl\` (the per-run counters the judge
prints; no new run). Summary: \`docs/perf/J7_GAP_SPLIT_summary.csv\`. Do not edit by hand.

## 1. Question

J5 and J6 give the ratio of \`ns_per_op\` per scenario. The same runs also carry the process's user time, kernel time, page faults and RSS. How much of
the sefer-minus-mimalloc gap is kernel work (faults, release and re-commit of memory) rather than user-side allocator code?

## 2. Method

Per scenario and arm, the median over all runs of the campaign (36 runs: 12 blocks x 3 repeats). Gap = sefer median minus mimalloc median. The three CPU
columns are whole-process counters of one run (they include the judge's own block bookkeeping, identical for both arms), \`ns_per_op\` is the judge's timed window.
\`end_rss\` is the resident size when the judge prints: mimalloc keeps its pages, so a large sefer-minus-mimalloc difference there is memory sefer gave back.
Clock-tick granularity of the CPU columns is 10 ms on Linux.

`;
const summary = [];
for (const [name, file] of PLAT) {
  const recs = load(file);
  md += `## ${name}\n\n| scenario | arm | ns/op | user ms | kernel ms | faults | peak RSS MiB | end RSS MiB |\n|---|---|---:|---:|---:|---:|---:|---:|\n`;
  for (const sc of SCEN) {
    const m = {};
    for (const arm of ['sefer', 'mi']) {
      const rs = recs.filter((r) => r.arm === arm && r.r.scenario === sc).map((r) => r.r);
      assert.ok(rs.length >= 12, `runs ${name} ${sc} ${arm}`);
      m[arm] = { n: rs.length, ns: med(rs.map((r) => r.ns_per_op)), user: med(rs.map((r) => r.user_ms)), kernel: med(rs.map((r) => r.kernel_ms)),
        faults: med(rs.map((r) => r.faults)), peak: med(rs.map((r) => r.peak_rss)) / 2 ** 20, end: med(rs.map((r) => r.end_rss)) / 2 ** 20 };
      const x = m[arm];
      md += `| ${sc} | ${arm} | ${f1(x.ns)} | ${x.user} | ${x.kernel} | ${x.faults} | ${f1(x.peak)} | ${f1(x.end)} |\n`;
      csv += `${name.split(',')[0]},${sc},${arm},${x.n},${x.ns},${x.user},${x.kernel},${x.faults},${f1(x.peak)},${f1(x.end)}\n`;
    }
    summary.push({ name, sc, dNs: m.sefer.ns - m.mi.ns, dUser: m.sefer.user - m.mi.user, dKernel: m.sefer.kernel - m.mi.kernel, dFaults: m.sefer.faults - m.mi.faults, dEnd: m.sefer.end - m.mi.end });
  }
  md += '\n';
}
md += `## Gap split (sefer minus mimalloc, medians)

| platform | scenario | d ns/op | d user ms | d kernel ms | d faults | d end RSS MiB |
|---|---|---:|---:|---:|---:|---:|
`;
for (const s of summary) {
  assert.ok([s.dNs, s.dUser, s.dKernel, s.dFaults, s.dEnd].every(Number.isFinite), 'finite');
  md += `| ${s.name.split(',')[0]} | ${s.sc} | ${f1(s.dNs)} | ${s.dUser} | ${s.dKernel} | ${s.dFaults} | ${f1(s.dEnd)} |\n`;
}
// Step 2: callgrind Ir per operation of the growth scenarios (docs/perf/j7/j7.sh, Linux judge of J6).
const irDir = 'j7/raw/';
const scale = readFileSync(new URL(`${irDir}scale.txt`, dir), 'utf8').trim();
md += `## Instructions per operation (callgrind, Linux, ${scale}, from \`docs/perf/j7/raw\`)

Whole-process totals divided by the judge's own \`ops\` (allocation and free calls); the judge's block bookkeeping (\`main\`, \`Run::alloc\`, \`Run::free\`) is
identical for both arms, so it is part of both columns. Sefer-specific functions are listed with their Ir per operation.

| scenario | sefer Ir/op | mimalloc Ir/op | sefer minus mimalloc | sefer functions (Ir/op) |
|---|---:|---:|---:|---|
`;
csv += 'callgrind,scenario,sefer_ir_per_op,mi_ir_per_op,delta_ir_per_op\n';
for (const sc of ['grow64', 'growmix', 'regrow']) {
  const ir = {};
  for (const arm of ['sefer', 'mi']) {
    const ops = JSON.parse(readFileSync(new URL(`${irDir}run.${sc}.${arm}.json`, dir), 'utf8')).ops;
    const txt = readFileSync(new URL(`${irDir}ir.${sc}.${arm}.txt`, dir), 'utf8');
    const total = Number(/^([\d,]+) \(100\.0%\)  PROGRAM TOTALS/m.exec(txt)[1].replace(/,/g, ''));
    assert.ok(ops > 0 && total > 0, `ops/total ${sc} ${arm}`);
    const fns = [...txt.matchAll(/^([\d,]+) \(\s*[\d.]+%\)  \?\?\?:(.*?) \[/gm)].map((m) => ({ ir: Number(m[1].replace(/,/g, '')), name: m[2] }));
    ir[arm] = { ops, total, per: total / ops, fns };
  }
  assert.equal(ir.sefer.ops, ir.mi.ops, `same op count ${sc}`);
  const own = ir.sefer.fns.filter((f) => f.name.includes('sefer_alloc')).slice(0, 4)
    .map((f) => `${f.name.replace(/^<?sefer_alloc::(\w+::)*(\w+)>?::/, '').replace(/^<[^>]*>::/, '')} ${(f.ir / ir.sefer.ops).toFixed(1)}`).join('; ');
  const d = ir.sefer.per - ir.mi.per;
  assert.ok(Math.abs(d - (ir.sefer.total - ir.mi.total) / ir.sefer.ops) < 1e-6, 'delta arithmetic');
  md += `| ${sc} | ${f1(ir.sefer.per)} | ${f1(ir.mi.per)} | ${f1(d)} (${((ir.sefer.per / ir.mi.per - 1) * 100).toFixed(1)} % of ${f1(ir.mi.per)}) | ${own} |\n`;
  csv += `callgrind,${sc},${f1(ir.sefer.per)},${f1(ir.mi.per)},${f1(d)}\n`;
}
md += '\n';
// Step 3: line-level self Ir of find_segment_with_free_impl in grow64 (docs/perf/j7/lines.mjs, calls.mjs on the gzipped callgrind dumps).
function profile(gzName, fnPat) {
  const lines = gunzipSync(readFileSync(new URL(`${irDir}${gzName}`, dir))).toString('utf8').split(/\r?\n/);
  let file = '', inFn = false, inCall = false, callee = '', calls = 0;
  const cost = new Map();
  for (const l of lines) {
    if (l.startsWith('fl=') || l.startsWith('fi=') || l.startsWith('fe=')) { file = l.slice(3); continue; }
    if (l.startsWith('fn=')) { inFn = l.slice(3).includes(fnPat); inCall = false; continue; }
    if (l.startsWith('cfn=')) { callee = l.slice(4); continue; }
    if (l.startsWith('calls=')) { if (callee.includes(fnPat)) calls += Number(l.slice(6).split(' ')[0]); inCall = true; continue; }
    if (/^\d+ \d+/.test(l)) {
      if (inCall) { inCall = false; continue; }
      if (!inFn) continue;
      const [ln, c] = l.split(' ').map(Number);
      const k = `${file.replace(/^.*\/(src|crates|examples)\//, '$1/')}:${ln}`;
      cost.set(k, (cost.get(k) ?? 0) + c);
    }
  }
  const total = [...cost.values()].reduce((a, b) => a + b, 0);
  return { calls, total, top: [...cost.entries()].sort((a, b) => b[1] - a[1]).slice(0, 6) };
}
md += `## Where the discovery cost sits (callgrind with line tables, grow64, \`find_segment_with_free_impl\`)

\`docs/perf/j7/raw/grow64.sefer*.lines.out.gz\` (\`--dump-line=yes --compress-strings=no --compress-pos=no\`, a judge build with \`CARGO_PROFILE_RELEASE_DEBUG=line-tables-only\` of main \`633ad41b\`,
whose source differs from the J6 build only in docs); lines from \`docs/perf/j7/lines.mjs\`, call counts from \`docs/perf/j7/calls.mjs\`.

| scale | calls | self Ir (inlined callees included) | Ir per call | hottest lines (self Ir) |
|---|---:|---:|---:|---|
`;
for (const [label, gz] of [['0.1 (25 segments)', 'grow64.sefer.lines.out.gz'], ['0.5 (128 segments)', 'grow64.sefer.s05.lines.out.gz']]) {
  const p = profile(gz, 'find_segment_with_free_impl');
  assert.ok(p.calls > 0 && p.total > 0, `profile ${gz}`);
  md += `| ${label} | ${p.calls} | ${p.total} | ${f1(p.total / p.calls)} | ${p.top.slice(0, 5).map(([k, c]) => `${k} ${f1(c / p.calls)}`).join('; ')} |\n`;
}
md += `
Reading: one call per magazine refill (16 blocks); at 0.5 the per-call cost is dominated by the walk over the 64 directory words of the class that
\`os::read_directory_class_words\` copies by value (\`scan.rs\` lines around 526–533 and the slice/pointer iterator frames), almost all of them zero while the heap only grows.
That cost is the same for every refill whatever the heap holds, so it is the candidate for step J8 (skip all-zero words in chunks; same bits, same order).

`;
const kernelLed = summary.filter((s) => s.dKernel > 0 && s.dKernel >= s.dUser && s.dNs > 0).map((s) => `${s.name.split(',')[0]} ${s.sc}`);
md += `
## Reading

- Cells where sefer is slower and the kernel-time gap is at least the user-time gap: ${kernelLed.length ? kernelLed.join('; ') : 'none'}.
- A negative \`d end RSS\` means sefer returned memory that mimalloc still holds when the judge prints (retention policy, RET-1), not allocator speed.
- The CPU columns are process totals, so they bound the question; they do not replace a per-function attribution (perf / callgrind), which is the next J7 step.
`;
writeFileSync(new URL('J7_GAP_SPLIT.md', dir), md);
writeFileSync(new URL('J7_GAP_SPLIT_summary.csv', dir), csv);
console.log(md.split('\n').filter((l) => l.startsWith('| Linux') || l.startsWith('| Windows') || l.startsWith('- Cells')).join('\n'));
