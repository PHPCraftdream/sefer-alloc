const FLAG_TO_KEY = {
  '--base': 'base',
  '--head': 'head',
  '--log': 'log',
  '--commit': 'commit',
  '--base-commit': 'baseCommit',
  '--features': 'features',
  '--profile': 'profile',
  '--note': 'note',
  '--csv': 'csv',
  '--md': 'md',
};
const VALUE_FLAGS = new Set(Object.keys(FLAG_TO_KEY));

function parseCliArgs(argv) {
  const opts = {};
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i];
    if (!VALUE_FLAGS.has(flag)) {
      return { error: `unknown or misplaced argument: ${flag}` };
    }
    if (i + 1 >= argv.length) {
      return { error: `${flag} requires a value` };
    }
    const key = FLAG_TO_KEY[flag];
    if (opts[key] !== undefined) {
      return { error: `${flag} given more than once` };
    }
    opts[key] = argv[++i];
  }
  return { opts };
}

function emitOutput(path, text) {
  if (path) writeFileSync(path, text);
  else process.stdout.write(text);
}

/**
 * CLI entry point. Returns the process exit code: 0 ok, 1 parse/compare/IO
 * failure (message prefixed `[iai-nolto-summary] FAIL — ` on stderr), 2 usage
 * violation (usage printed to stderr). On success prints the one-line OK
 * status to stderr, then emits the CSV and markdown outputs (stdout by
 * default, so stdout stays clean for piping).
 */
export function main(argv = process.argv.slice(2)) {
  const { opts, error } = parseCliArgs(argv);
  if (error) {
    console.error(`[iai-nolto-summary] ${error}\n${USAGE}`);
    return 2;
  }
  const hasLog = opts.log !== undefined;
  const hasBase = opts.base !== undefined;
  const hasHead = opts.head !== undefined;
  if (hasLog && (hasBase || hasHead)) {
    console.error(`[iai-nolto-summary] --log cannot be combined with --base/--head\n${USAGE}`);
    return 2;
  }
  if (hasBase !== hasHead) {
    console.error(`[iai-nolto-summary] --base and --head must be given together\n${USAGE}`);
    return 2;
  }
  if (!hasLog && !hasBase) {
    console.error(
      `[iai-nolto-summary] exactly one mode is required: --log <file> OR --base <file> --head <file>\n${USAGE}`,
    );
    return 2;
  }
  const mode = hasLog ? 'record' : 'compare';
  const meta = {
    commit: opts.commit ?? null,
    baseCommit: opts.baseCommit ?? null,
    features: opts.features ?? DEFAULT_FEATURES,
    profile: opts.profile ?? DEFAULT_PROFILE,
    note: opts.note ?? null,
  };
  let rows;
  let compare;
  try {
    if (mode === 'record') {
      rows = parseIaiLog(readFileSync(opts.log, 'utf8'));
    } else {
      const baseRows = parseIaiLog(readFileSync(opts.base, 'utf8'));
      const headRows = parseIaiLog(readFileSync(opts.head, 'utf8'));
      compare = compareRuns(baseRows, headRows);
    }
  } catch (e) {
    console.error(`[iai-nolto-summary] FAIL — ${e.message}`);
    return 1;
  }
  const csvText = mode === 'record' ? buildCsv(rows, meta) : buildCompareCsv(compare, meta);
  const mdText = buildMarkdownSection(mode === 'record' ? { rows, meta } : { compare, meta });
  const benchCount = mode === 'record' ? rows.length : compare.rows.length;
  console.error(`[iai-nolto-summary] OK — ${benchCount} bench(es), mode=${mode}`);
  try {
    // "-" as the --csv/--md value means stdout (same convention for both).
    emitOutput(!opts.csv || opts.csv === '-' ? undefined : opts.csv, csvText);
    emitOutput(!opts.md || opts.md === '-' ? undefined : opts.md, `${mdText}\n`);
  } catch (e) {
    console.error(`[iai-nolto-summary] FAIL — writing output failed: ${e.message}`);
    return 1;
  }
  return 0;
}

// ESM CLI guard: run main() only when executed directly (not when imported by
// the node:test suite).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main();
}
