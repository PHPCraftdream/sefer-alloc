/** Thousands separators, "-" for null (scripts/iai.mjs's fmt convention). */
const fmtN = (n) => (n == null ? '-' : n.toLocaleString('en-US'));
const fmtPct = (n) => (n == null ? '-' : `${n.toLocaleString('en-US')}%`);

/**
 * A fenced markdown block: `### <title>` heading, provenance bullets (only
 * those provided in meta), then the mode's table. Compare mode additionally
 * renders the totals line, whose X/Y/Z strings are assert-checked against
 * sums recomputed from the rows (independent of compare.totals).
 */
export function buildMarkdownSection({ rows, compare, meta = {}, title = DEFAULT_TITLE } = {}) {
  if (!rows && !compare) {
    throw new Error('buildMarkdownSection: pass rows (record mode) or compare (compare mode)');
  }
  const out = ['```', `### ${title}`, ''];
  const bullets = [
    ['commit', meta.commit],
    ['base commit', meta.baseCommit],
    ['features', meta.features],
    ['profile', meta.profile],
    ['note', meta.note],
  ]
    .filter(([, v]) => v != null)
    .map(([k, v]) => `- ${k}: ${v}`);
  if (bullets.length > 0) out.push(...bullets, '');
  if (compare) {
    out.push('| bench | Ir base | Ir head | Δ Ir | Δ % |');
    out.push('| --- | --- | --- | --- | --- |');
    for (const r of compare.rows) {
      out.push(
        `| ${r.name} | ${fmtN(r.irBase)} | ${fmtN(r.irHead)} | ${fmtN(r.deltaIr)} | ${fmtPct(r.deltaPct)} |`,
      );
    }
    // Totals line + arithmetic self-check: recompute the sums from the rows
    // and assert both compare.totals and the rendered strings agree.
    const sumBase = compare.rows.reduce((s, r) => s + r.irBase, 0);
    const sumHead = compare.rows.reduce((s, r) => s + r.irHead, 0);
    const sumDelta = compare.rows.reduce((s, r) => s + r.deltaIr, 0);
    const totalsLine = `Total Ir base/head/delta: ${fmtN(sumBase)} / ${fmtN(sumHead)} / ${fmtN(sumDelta)}`;
    assert.deepEqual(
      { sumBase, sumHead, sumDelta },
      {
        sumBase: compare.totals.sumBase,
        sumHead: compare.totals.sumHead,
        sumDelta: compare.totals.sumDelta,
      },
      'markdown totals disagree with compare.totals',
    );
    assert.equal(
      totalsLine,
      `Total Ir base/head/delta: ${fmtN(compare.totals.sumBase)} / ${fmtN(compare.totals.sumHead)} / ${fmtN(compare.totals.sumDelta)}`,
      'rendered totals line disagrees with the recomputed sums',
    );
    out.push(totalsLine);
  } else {
    out.push('| bench | Ir | L1 hits | L2 hits | RAM hits | Est. cycles |');
    out.push('| --- | --- | --- | --- | --- | --- |');
    for (const r of rows) {
      out.push(
        `| ${r.name} | ${fmtN(r.ir)} | ${fmtN(r.l1)} | ${fmtN(r.l2)} | ${fmtN(r.ram)} | ${fmtN(r.cycles)} |`,
      );
    }
  }
  out.push('```');
  return out.join('\n');
}

