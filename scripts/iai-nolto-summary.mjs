// ---------------------------------------------------------------------------
// Parsing (mirrors scripts/iai.mjs's parseMetrics — credited)
// ---------------------------------------------------------------------------

// VERBATIM from scripts/iai.mjs parseMetrics (the proven reader of
// iai-callgrind 0.14 stdout): bench header lines and the five metric-row
// patterns. The first integer column (possibly thousands-separated) of a
// metric row is the current run's absolute count, baseline-independent.
const BENCH_HEADER_RE = /^([A-Za-z_][\w]*::)+([A-Za-z_]\w*)\b/;
const metricRowRe = (label) => new RegExp(`^\\s*${label}:\\s*([\\d,]+)`);
const INSTR_RE = metricRowRe('Instructions');
const L1_RE = metricRowRe('L1 Hits');
const L2_RE = metricRowRe('L2 Hits');
const RAM_RE = metricRowRe('RAM Hits');
const CYCLES_RE = metricRowRe('Estimated Cycles');

// GitHub Actions log normalization: a raw downloaded Actions log line may be
// prefixed with tab-separated job/step fields and/or a leading ISO-8601
// timestamp. Strip those and NOTHING else — the header/metric regexes above
// must still anchor exactly as in scripts/iai.mjs.
const ACTIONS_TS_RE = /^\d{4}-\d{2}-\d{2}T[\d:.]+Z?\s+/;

/** Strip leading tab-separated fields and a leading ISO-8601 timestamp. */
function normalizeActionsLine(line) {
  let l = line;
  for (;;) {
    const m = /^[^\t]*\t/.exec(l);
    if (!m) break;
    l = l.slice(m[0].length);
  }
  return l.replace(ACTIONS_TS_RE, '');
}

const numFrom = (m) => Number(m[1].replace(/,/g, ''));

/**
 * Parse iai-callgrind 0.14 stdout (or a downloaded GitHub Actions log of the
 * same) into per-bench rows `{ name, ir, l1, l2, ram, cycles }`, in first
 * occurrence order (de-duped by name, keeping the FIRST block, exactly like
 * scripts/iai.mjs). Cache rows may be absent per bench (null) — older
 * callgrind builds / `--cache-sim=no` omit them; that stays non-fatal,
 * exactly like scripts/iai.mjs.
 *
 * Deliberate STRICTNESS ADDITIONS over scripts/iai.mjs (this is a
 * baseline-recording tool, so silent data loss is corruption):
 *   - a bench header that never produced an `Instructions:` row is a hard
 *     error — one Error listing every such bench name;
 *   - every parsed Ir must be a finite non-negative integer.
 */
export function parseIaiLog(text) {
  const lines = text.split(/\r?\n/);
  const results = [];
  const dropped = [];
  let current = null;
  let currentHasIr = false;
  const closeBench = () => {
    if (current !== null && !currentHasIr) dropped.push(current);
  };
  for (const rawLine of lines) {
    const line = normalizeActionsLine(rawLine);
    const h = BENCH_HEADER_RE.exec(line);
    if (h) {
      closeBench();
      current = h[2];
      currentHasIr = false;
      continue;
    }
    const im = INSTR_RE.exec(line);
    if (im && current) {
      const ir = numFrom(im);
      if (!Number.isFinite(ir) || !Number.isInteger(ir) || ir < 0) {
        throw new Error(
          `iai log: bench "${current}" has a non-integer/negative Instructions value "${im[1]}"`,
        );
      }
      currentHasIr = true;
      results.push({ name: current, ir, l1: null, l2: null, ram: null, cycles: null });
      // Keep `current` pointing at this bench so the cache rows that follow
      // (no header between them and the Instructions row) attach to it.
      continue;
    }
    // Cache rows attach to the most-recently produced bench (scripts/iai.mjs).
    if (current !== null && results.length > 0) {
      const last = results[results.length - 1];
      if (last.name === current) {
        let m;
        if ((m = L1_RE.exec(line))) last.l1 = numFrom(m);
        else if ((m = L2_RE.exec(line))) last.l2 = numFrom(m);
        else if ((m = RAM_RE.exec(line))) last.ram = numFrom(m);
        else if ((m = CYCLES_RE.exec(line))) last.cycles = numFrom(m);
      }
    }
  }
  closeBench();
  if (dropped.length > 0) {
    throw new Error(
      `iai log: ${dropped.length} bench header(s) produced no Instructions row ` +
        `(dropped benches would corrupt baseline deltas): ${dropped.join(', ')}`,
    );
  }
  // De-dupe by name, keep first occurrence (one block per bench).
  const seen = new Set();
  return results.filter((r) => (seen.has(r.name) ? false : seen.add(r.name)));
}

