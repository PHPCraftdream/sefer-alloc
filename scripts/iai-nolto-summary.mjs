/**
 * Compare two parseIaiLog results. Bench-name sets must be EQUAL (a mismatch
 * throws one Error listing `only in base: [...]` / `only in head: [...]`).
 * Returns `{ rows, totals }` where each row carries both sides' cache fields
 * plus `deltaIr = irHead - irBase` and
 * `deltaPct = irBase === 0 ? null : Math.round((delta/irBase)*10000)/100`
 * (two decimals), and `totals` holds the sums over all benches.
 */
export function compareRuns(baseRows, headRows) {
  const baseNames = baseRows.map((r) => r.name);
  const headNames = headRows.map((r) => r.name);
  const headSet = new Set(headNames);
  const baseSet = new Set(baseNames);
  const onlyBase = baseNames.filter((n) => !headSet.has(n));
  const onlyHead = headNames.filter((n) => !baseSet.has(n));
  if (onlyBase.length > 0 || onlyHead.length > 0) {
    throw new Error(
      'iai compare: bench-name sets differ — ' +
        `only in base: [${onlyBase.join(', ')}]; only in head: [${onlyHead.join(', ')}]`,
    );
  }
  const headByName = new Map(headRows.map((r) => [r.name, r]));
  const rows = baseRows.map((b) => {
    const h = headByName.get(b.name);
    const deltaIr = h.ir - b.ir;
    const deltaPct =
      b.ir === 0 ? null : Math.round((deltaIr / b.ir) * 10000) / 100;
    return {
      name: b.name,
      irBase: b.ir,
      irHead: h.ir,
      deltaIr,
      deltaPct,
      l1Base: b.l1,
      l2Base: b.l2,
      ramBase: b.ram,
      cyclesBase: b.cycles,
      l1Head: h.l1,
      l2Head: h.l2,
      ramHead: h.ram,
      cyclesHead: h.cycles,
    };
  });
  const totals = {
    sumBase: rows.reduce((s, r) => s + r.irBase, 0),
    sumHead: rows.reduce((s, r) => s + r.irHead, 0),
    sumDelta: rows.reduce((s, r) => s + r.deltaIr, 0),
  };
  return { rows, totals };
}

// ---------------------------------------------------------------------------
// CSV emission + self-check (the generated text is re-parsed and assert-checked)
// ---------------------------------------------------------------------------

const RECORD_HEADER = [
  'bench', 'ir', 'l1', 'l2', 'ram', 'cycles',
  'commit', 'features', 'profile', 'note',
];
const COMPARE_HEADER = [
  'bench', 'ir_base', 'ir_head', 'delta_ir', 'delta_pct',
  'l1_base', 'l2_base', 'ram_base', 'cycles_base',
  'l1_head', 'l2_head', 'ram_head', 'cycles_head',
  'commit_base', 'commit_head', 'features', 'profile', 'note',
];
const TOTALS_BENCH = 'TOTAL';

/** RFC-4180-style field: quote when it contains comma, quote or newline. */
export function csvField(v) {
  if (v == null) return '';
  const s = String(v);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/**
 * Minimal CSV reader (dependency-free, quoted-field aware) returning
 * string[][]. Handles "..." quoting with "" escapes and embedded newlines;
 * CRLF and LF both terminate rows; a trailing newline adds no empty row.
 */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  const pushField = () => {
    row.push(field);
    field = '';
  };
  const pushRow = () => {
    pushField();
    rows.push(row);
    row = [];
  };
  const n = text.length;
  let i = 0;
  while (i < n) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
        } else {
          inQuotes = false;
          i += 1;
        }
      } else {
        field += c;
        i += 1;
      }
    } else if (c === '"' && field === '') {
      inQuotes = true;
      i += 1;
    } else if (c === ',') {
      pushField();
      i += 1;
    } else if (c === '\r') {
      if (text[i + 1] === '\n') i += 1;
      pushRow();
      i += 1;
    } else if (c === '\n') {
      pushRow();
      i += 1;
    } else {
      field += c;
      i += 1;
    }
  }
  if (field !== '' || row.length > 0) pushRow();
  return rows;
}

/** Empty cell -> null; numeric cell -> Number (CSV carries bare numbers). */
const cellNum = (cell) => (cell === '' ? null : Number(cell));

function assertFieldCounts(parsed, width, what) {
  for (let i = 0; i < parsed.length; i++) {
    assert.equal(
      parsed[i].length,
      width,
      `${what}: row ${i} has ${parsed[i].length} fields, header has ${width}`,
    );
  }
}

const pctOf = (delta, base) =>
  base === 0 ? null : Math.round((delta / base) * 10000) / 100;

/**
 * SELF-CHECK (mandatory arithmetic audit): re-parse the generated CSV text
 * with parseCsv and assert (a) field counts, (b) values round-trip to the
 * in-memory rows, (c) delta arithmetic holds for every row re-read from the
 * text, (d) the final TOTAL row equals the sums recomputed from the CSV
 * per-bench rows.
 */
function selfCheckRecordCsv(csvText, rows, meta) {
  const parsed = parseCsv(csvText);
  assert.equal(parsed.length, rows.length + 1, 'record CSV: row count');
  assert.deepEqual(parsed[0], RECORD_HEADER, 'record CSV: header mismatch');
  assertFieldCounts(parsed, RECORD_HEADER.length, 'record CSV');
  for (let i = 0; i < rows.length; i++) {
    const r = rows[i];
    const p = parsed[i + 1];
    assert.equal(p[0], r.name, `record CSV row ${i}: bench name round-trip`);
    assert.deepEqual(
      p.slice(1, 6).map(cellNum),
      [r.ir, r.l1, r.l2, r.ram, r.cycles],
      `record CSV row ${i} (${r.name}): metrics do not round-trip`,
    );
    assert.deepEqual(
      p.slice(6),
      [meta.commit ?? '', meta.features ?? '', meta.profile ?? '', meta.note ?? ''],
      `record CSV row ${i} (${r.name}): identity cells do not round-trip`,
    );
  }
}

function selfCheckCompareCsv(csvText, compare, meta) {
  const parsed = parseCsv(csvText);
  assert.equal(
    parsed.length,
    compare.rows.length + 2,
    'compare CSV: row count (header + benches + TOTAL)',
  );
  assert.deepEqual(parsed[0], COMPARE_HEADER, 'compare CSV: header mismatch');
  assertFieldCounts(parsed, COMPARE_HEADER.length, 'compare CSV');
  let sumBase = 0;
  let sumHead = 0;
  let sumDelta = 0;
  for (let i = 0; i < compare.rows.length; i++) {
    const r = compare.rows[i];
    const p = parsed[i + 1];
    const irBase = cellNum(p[1]);
    const irHead = cellNum(p[2]);
    const delta = cellNum(p[3]);
    const pct = cellNum(p[4]);
    assert.equal(p[0], r.name, `compare CSV row ${i}: bench name round-trip`);
    // (b) values re-parsed from the CSV text equal the in-memory values:
    assert.deepEqual(
      [irBase, irHead, delta],
      [r.irBase, r.irHead, r.deltaIr],
      `compare CSV row ${i} (${r.name}): Ir columns do not round-trip`,
    );
    assert.deepEqual(
      p.slice(5, 13).map(cellNum),
      [r.l1Base, r.l2Base, r.ramBase, r.cyclesBase, r.l1Head, r.l2Head, r.ramHead, r.cyclesHead],
      `compare CSV row ${i} (${r.name}): cache columns do not round-trip`,
    );
    // (c) arithmetic re-checked from the CSV text alone:
    assert.equal(
      delta,
      irHead - irBase,
      `compare CSV row ${i} (${r.name}): delta_ir != ir_head - ir_base`,
    );
    assert.equal(
      pct,
      pctOf(irHead - irBase, irBase),
      `compare CSV row ${i} (${r.name}): delta_pct != the two-decimal formula`,
    );
    assert.deepEqual(
      p.slice(13),
      [meta.baseCommit ?? '', meta.commit ?? '', meta.features ?? '', meta.profile ?? '', meta.note ?? ''],
      `compare CSV row ${i} (${r.name}): identity cells do not round-trip`,
    );
    sumBase += irBase;
    sumHead += irHead;
    sumDelta += delta;
  }
  // (d) the final TOTAL row equals the sums recomputed from the per-bench
  // rows IN THE CSV TEXT (and the in-memory totals):
  const t = parsed[parsed.length - 1];
  assert.equal(t[0], TOTALS_BENCH, 'compare CSV: last row is not the TOTAL row');
  assert.deepEqual(
    [cellNum(t[1]), cellNum(t[2]), cellNum(t[3])],
    [sumBase, sumHead, sumDelta],
    'compare CSV: TOTAL row != sums recomputed from the per-bench CSV rows',
  );
  assert.equal(
    cellNum(t[4]),
    pctOf(sumDelta, sumBase),
    'compare CSV: TOTAL delta_pct != the two-decimal formula on the recomputed sums',
  );
  assert.deepEqual(
    [cellNum(t[1]), cellNum(t[2]), cellNum(t[3])],
    [compare.totals.sumBase, compare.totals.sumHead, compare.totals.sumDelta],
    'compare CSV: TOTAL row != in-memory totals',
  );
}

/**
 * Single-record CSV: one row per bench in parse order (+ the identity meta).
 * The text is self-checked (see selfCheckRecordCsv) before being returned.
 */
export function buildCsv(rows, meta = {}) {
  const lines = [RECORD_HEADER.join(',')];
  for (const r of rows) {
    lines.push(
      [
        r.name, r.ir, r.l1, r.l2, r.ram, r.cycles,
        meta.commit ?? '', meta.features ?? '', meta.profile ?? '', meta.note ?? '',
      ]
        .map(csvField)
        .join(','),
    );
  }
  const csv = lines.join('\n') + '\n';
  selfCheckRecordCsv(csv, rows, meta);
  return csv;
}

/**
 * Compare CSV: one row per bench in base parse order, then a final TOTAL row
 * (sums over the per-bench rows; cache/identity cells empty). Self-checked.
 */
export function buildCompareCsv(compare, meta = {}) {
  const toLine = (r) =>
    [
      r.name, r.irBase, r.irHead, r.deltaIr, r.deltaPct,
      r.l1Base, r.l2Base, r.ramBase, r.cyclesBase,
      r.l1Head, r.l2Head, r.ramHead, r.cyclesHead,
      meta.baseCommit ?? '', meta.commit ?? '',
      meta.features ?? '', meta.profile ?? '', meta.note ?? '',
    ]
      .map(csvField)
      .join(',');
  const t = compare.totals;
  const lines = [COMPARE_HEADER.join(',')];
  for (const r of compare.rows) lines.push(toLine(r));
  lines.push(
    toLine({
      name: TOTALS_BENCH,
      irBase: t.sumBase,
      irHead: t.sumHead,
      deltaIr: t.sumDelta,
      deltaPct: pctOf(t.sumDelta, t.sumBase),
      l1Base: null, l2Base: null, ramBase: null, cyclesBase: null,
      l1Head: null, l2Head: null, ramHead: null, cyclesHead: null,
    }),
  );
  const csv = lines.join('\n') + '\n';
  selfCheckCompareCsv(csv, compare, meta);
  return csv;
}

