// scripts/iai-nolto-summary.mjs — cargo-free summarizer for the no-LTO
// iai-callgrind CI row (step P1.0 of
// docs/plans/2026-11-15-workspace-restructure-plan.md).
//
// PURPOSE. The new `iai-callgrind-nolto` CI job (.github/workflows/perf-gate.yml)
// runs the SAME bench as the existing gate (`cargo bench --bench perf_gate_iai
// --features "production bench-internals internals"`) but overrides the bench
// profile via cargo env vars — CARGO_PROFILE_BENCH_LTO=false and
// CARGO_PROFILE_BENCH_CODEGEN_UNITS=16 — so the measured codegen is what a
// downstream library user gets by default (the repo's own `[profile.bench]` is
// lto="thin", codegen-units=1). This script turns that job's raw
// iai-callgrind 0.14 stdout into (a) a single-run CSV + markdown baseline
// record, or (b) a base-vs-head comparison of two such logs. It is
// CARGO-FREE: pure node (node:fs / node:url / node:assert only), it never
// shells out, and it parses iai-callgrind 0.14 stdout exactly like
// scripts/iai.mjs's proven parseMetrics (header/metric regexes credited
// verbatim below), plus GitHub Actions log-line prefix stripping.
//
// NEVER INVENTS NUMBERS. Every Ir/cache figure emitted here is read verbatim
// from the log file(s) passed on the command line; baseline values come ONLY
// from the CI log passed in. There are no hardcoded measurements, no
// estimates, and no fallback for missing data — a bench header whose
// `Instructions:` row never appears is a HARD ERROR (a silently dropped bench
// would corrupt baseline deltas), and base/head bench-name sets that differ
// are a HARD ERROR. The ONLY arithmetic performed is derived bookkeeping
// (deltas, percentages, totals), every line of which is assert-checked by
// re-parsing the generated CSV with this file's own parseCsv(). Local
// iai/valgrind runs are FORBIDDEN on this host (repo CLAUDE.md; Valgrind is
// Linux-only and cargo build/bench/run are banned locally) — the numbers come
// from GitHub CI logs.
//
// USAGE (exact examples):
//   # single-record mode — one iai stdout log (e.g. a downloaded Actions log):
//   node scripts/iai-nolto-summary.mjs --log iai-nolto-run.txt --commit <sha> --note "first no-LTO baseline"
//   # same run, writing the artifacts to files instead of stdout:
//   node scripts/iai-nolto-summary.mjs --log iai-nolto-run.txt --csv out.csv --md out.md
//   # compare mode — two logs; identical bench-name sets are required:
//   node scripts/iai-nolto-summary.mjs --base old-run.txt --head new-run.txt --commit <head-sha> --base-commit <base-sha>
//
// FLAGS: --log <file> OR --base <file> --head <file> (exactly one mode;
// violations print usage to stderr and exit 2). Identity flags (all
// optional): --commit, --base-commit, --features (default
// "production bench-internals internals"), --profile (default "bench profile
// + CARGO_PROFILE_BENCH_LTO=false + CARGO_PROFILE_BENCH_CODEGEN_UNITS=16
// (cargo env overrides of [profile.bench]; user-default codegen)"), --note.
// Output flags: --csv <path> (default: print to stdout), --md <path|->
// ("-" or omitted = print to stdout). Exit codes: 0 ok, 1 parse/compare/IO
// failure, 2 usage violation. The `[iai-nolto-summary] OK/FAIL` status line
// goes to stderr so stdout stays clean for piping.

