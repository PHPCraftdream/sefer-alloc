#!/usr/bin/env node
// Derives the P1-6 C‴ gate report tables from one run directory (verdict.txt,
// summary.csv, input.json). Every printed number is recomputed here from the
// raw rows and asserted against the frozen judge's own verdict. Markdown goes
// to report_tables.md, the key numbers to the report's companion summary CSV.
//
//   node scripts/r20_prf01_c3_report_tables.mjs <run-dir> > <run-dir>/report_tables.md
//   node scripts/r20_prf01_c3_report_tables.mjs <run-dir> --csv > docs/perf/R20_PRF01_C3_RUN01_REPORT_summary.csv
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const dir = process.argv[2];
const csvMode = process.argv[3] === '--csv';
assert.ok(dir, 'usage: r20_prf01_c3_report_tables.mjs <run-dir> [--csv]');
const read = name => fs.readFileSync(path.join(dir, name), 'utf8');
// The committed run dir holds input.json.gz; a downloaded artifact holds input.json.
const readJson = name =>
  JSON.parse(
    fs.existsSync(path.join(dir, name))
      ? read(name)
      : zlib.gunzipSync(fs.readFileSync(path.join(dir, `${name}.gz`))).toString('utf8'),
  );

const verdictText = read('verdict.txt');
const verdict = JSON.parse(verdictText.slice(verdictText.indexOf('{')));
const input = readJson('input.json');
const env = read('environment.log');
const host = env.split('\n').find(l => l.startsWith('Linux '));
const valgrind = env.split('\n').find(l => l.startsWith('valgrind-'));
const rustc = env.split('\n').find(l => l.startsWith('rustc '));
assert.ok(host && valgrind && rustc, 'environment.log lacks host/valgrind/rustc lines');
const [baseCommit, candidateCommit] = input.ancestry.chain;
assert.equal(input.ancestry.result, 'A ancestor B');
const records = [];
const rec = (check, A, B, irA, irB, delta, denominator, limit, pass) => {
  assert.equal(delta, irB - irA, `${check}: delta`);
  records.push([check, A, B, irA, irB, delta, denominator ?? '', limit, pass ? 'pass' : 'FAIL']);
};
const csvRows = read('summary.csv').trim().split('\n').slice(1).map(line => {
  const [target, arm, name, ir, binarySha256] = line.split(',');
  return { target, arm, name, ir: BigInt(ir), binarySha256 };
});

const csv = (name, arm) => {
  const hits = csvRows.filter(r => r.name === name && r.arm === arm);
  assert.equal(hits.length, 1, `summary.csv row ${name}/${arm}`);
  return hits[0];
};
const row = (name, arm) => {
  const hits = input.iai.filter(r => r.name === name && r.arm === arm);
  assert.equal(hits.length, 1, `input.json row ${name}/${arm}`);
  const r = hits[0];
  assert.equal(BigInt(r.Ir), csv(name, arm).ir, `summary.csv disagrees with input.json for ${name}/${arm}`);
  return r;
};
const ir = (name, arm) => BigInt(row(name, arm).Ir);
const judged = (name, A, B) => {
  const hits = verdict.tables.iai.filter(r => r.name === name && r.A === A && r.B === B);
  assert.equal(hits.length, 1, `verdict row ${name} ${B} vs ${A}`);
  return hits[0];
};
const fmt = n => {
  const s = (n < 0n ? -n : n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  return n < 0n ? `−${s}` : s;
};
const signed = n => (n > 0n ? `+${fmt(n)}` : fmt(n));
// Exact decimal of num/den to `places` digits, rounded half up (no floats).
const ratio = (num, den, places = 3) => {
  assert.ok(den > 0n);
  const neg = num < 0n;
  const scale = 10n ** BigInt(places);
  const q = ((neg ? -num : num) * scale * 2n + den) / (den * 2n);
  const s = q.toString().padStart(places + 1, '0');
  return `${neg ? '−' : ''}${s.slice(0, -places)}.${s.slice(-places)}`;
};
const PAIRS = [['A1', 'B1'], ['A1', 'B2'], ['A2', 'B1'], ['A2', 'B2']];

const out = [];
const line = s => out.push(s);

line(`<!-- generated by scripts/r20_prf01_c3_report_tables.mjs from ${path.basename(dir)}; do not edit by hand -->`);
line('');
line(`Verdict: **${verdict.verdict}** (mode1 ${verdict.modes.mode1}, mode2 iai ${verdict.modes.mode2Iai}, mode2 native ${verdict.modes.mode2Native}); rehearsal = ${verdict.rehearsal}.`);
assert.equal(verdict.rehearsal, false);
line('');

// Benefit (mode 1).
line('### Benefit cells (mode 1)');
line('');
line('| Cell | Ir A1 | Ir B1 | B1/A1 | Limit | Judge |');
line('|---|---:|---:|---:|---|---|');
for (const name of ['multiseg_cold_256k', 'seg_cycle_decommit_256k']) {
  const a = ir(name, 'A1');
  const b = ir(name, 'B1');
  const j = judged(name, 'A1', 'B1');
  assert.equal(BigInt(j.delta), b - a);
  assert.equal(j.pass, 4n * b <= a);
  rec(`${name} B/A`, 'A1', 'B1', a, b, b - a, a, 'B/A <= 0.25', j.pass);
  line(`| \`${name}\` | ${fmt(a)} | ${fmt(b)} | ${fmt(b)} / ${fmt(a)} = ${ratio(b, a)} | ≤ 0.25 | ${j.pass ? 'pass' : 'FAIL'} |`);
}
for (const s of verdict.tables.slope) {
  const num = BigInt(s.numerator);
  const den = BigInt(s.denominator);
  const arm = s.arm;
  assert.equal(num, ir('growth16_4n', arm) - ir('growth16_2n', arm));
  assert.equal(den, ir('growth16_2n', arm) - ir('growth16_n', arm));
  assert.equal(s.pass, 2n * num <= 5n * den);
  rec('growth16 slope: value_b = 4n-2n, value_a = 2n-n', arm, arm, den, num, num - den, den, 'slope <= 2.5', s.pass);
  line(`| \`growth16\` slope ${arm} | — | — | (4n−2n) / (2n−n) = ${fmt(num)} / ${fmt(den)} = ${ratio(num, den)} | ≤ 2.5 | ${s.pass ? 'pass' : 'FAIL'} |`);
}
line('');

// Price (mode 2).
line('### Price cells (mode 2)');
line('');
line('| Cell | Ir A1 | Ir B1 | Δ (B1−A1) | Per remote free | Budget | Judge |');
line('|---|---:|---:|---:|---:|---|---|');
const producers = [
  ['r19_prf01_joined_producer_same_word', 6n],
  ['r20_prf01_c3_producer_distinct_words', 10n],
];
for (const [name, budget] of producers) {
  const a = ir(name, 'A1');
  const b = ir(name, 'B1');
  const frees = BigInt(row(name, 'B1').config.requested.workCount);
  assert.equal(frees, 4096n);
  const j = judged(name, 'A1', 'B1');
  assert.equal(BigInt(j.delta), b - a);
  assert.equal(j.pass, b - a <= budget * frees);
  rec(`${name} per remote free`, 'A1', 'B1', a, b, b - a, frees, `delta/frees <= +${budget}`, j.pass);
  line(`| \`${name}\` | ${fmt(a)} | ${fmt(b)} | ${signed(b - a)} | ${signed(b - a)} / ${fmt(frees)} = ${ratio(b - a, frees, 4)} | ≤ +${budget} | ${j.pass ? 'pass' : 'FAIL'} |`);
}
for (const name of ['r20_prf01_c3_remote_large_free', 'r20_prf01_strict_trim_payload', 'r20_prf01_bounded_maintenance', 'r19_prf01_publication']) {
  const a = ir(name, 'A1');
  const b = ir(name, 'B1');
  const j = judged(name, 'A1', 'B1');
  assert.equal(BigInt(j.delta), b - a);
  const budget = name === 'r19_prf01_publication' ? 'net B ≤ A' : 'abs(Δ) ≤ T_s';
  rec(name, 'A1', 'B1', a, b, b - a, null, budget, j.pass);
  line(`| \`${name}\` | ${fmt(a)} | ${fmt(b)} | ${signed(b - a)} | — | ${budget} | ${j.pass ? 'pass' : 'FAIL'} |`);
}
for (const c of verdict.tables.construction) {
  const a = ir(c.cell, 'A1');
  const b = ir(c.cell, 'B1');
  assert.equal(BigInt(c.arms.A1), a);
  assert.equal(BigInt(c.arms.B1), b);
  const r = c.checks.R_construct.find(x => x.pair === 'B1 vs A1');
  assert.equal(BigInt(r.delta), b - a);
  rec(`${c.cell} (construction)`, 'A1', 'B1', a, b, b - a, null, '<= 0 + T_s (10)', r.pass);
  line(`| \`${c.cell}\` (construction) | ${fmt(a)} | ${fmt(b)} | ${signed(b - a)} | — | 0 + T_s (10) | ${r.pass ? 'pass' : 'FAIL'} |`);
}
line('');

// Hot families.
line('### Hot families (per-operation slope)');
line('');
line('| Family | A1 n / 2n / 4n | B1 n / 2n / 4n | B1−A1 at n / 2n / 4n | slope Δ (all four pairs) | Judge |');
line('|---|---|---|---|---|---|');
for (const h of verdict.tables.hot) {
  const a = h.arms.A1;
  const b = h.arms.B1;
  for (const k of ['n', '2n', '4n']) assert.equal(BigInt(a[k]), ir(`r20_prf01_${h.family}_${k}`, 'A1'));
  const deltas = ['n', '2n', '4n'].map(k => BigInt(b[k]) - BigInt(a[k]));
  const slopes = [...new Set(h.checks.slope.map(s => s.slopeDelta))].join(', ');
  const pass = h.checks.slope.every(s => s.pass);
  line(`| \`${h.family}\` | ${['n', '2n', '4n'].map(k => fmt(BigInt(a[k]))).join(' / ')} | ${['n', '2n', '4n'].map(k => fmt(BigInt(b[k]))).join(' / ')} | ${deltas.map(signed).join(' / ')} | ${slopes} | ${pass ? 'pass' : 'FAIL'} |`);
}
line('');

// Mimalloc cells: exact zero across every cross pair.
line('### mimalloc cells (ΔIr = 0 required for every cross pair)');
line('');
const mimalloc = [...new Set(verdict.tables.iai.map(r => r.name).filter(n => n.startsWith('mimalloc_')))];
assert.equal(mimalloc.length, 13);
const nonzero = [];
for (const name of mimalloc) {
  for (const [A, B] of PAIRS) {
    const j = judged(name, A, B);
    assert.equal(BigInt(j.delta), ir(name, B) - ir(name, A));
    if (BigInt(j.delta) !== 0n) {
      rec(name, A, B, ir(name, A), ir(name, B), BigInt(j.delta), null, 'delta == 0', j.pass);
      nonzero.push({ name, A, B, delta: BigInt(j.delta), pass: j.pass });
    }
  }
}
line(`Pairs judged: ${mimalloc.length} cells × ${PAIRS.length} pairs = ${mimalloc.length * PAIRS.length}; non-zero: ${nonzero.length}.`);
line('');
if (nonzero.length) {
  line('| Cell | Pair | Δ | B binary = other B binary? | Judge |');
  line('|---|---|---:|---|---|');
  for (const z of nonzero) {
    const same = csv(z.name, 'B1').binarySha256 === csv(z.name, 'B2').binarySha256;
    line(`| \`${z.name}\` | ${z.B} vs ${z.A} | ${signed(z.delta)} | ${same ? 'yes (same sha256)' : 'no'} | ${z.pass ? 'pass' : 'FAIL'} |`);
  }
  line('');
  line('| Cell | A1 | A2 | B1 | B2 | C0 |');
  line('|---|---:|---:|---:|---:|---:|');
  for (const name of [...new Set(nonzero.map(z => z.name))]) {
    line(`| \`${name}\` | ${['A1', 'A2', 'B1', 'B2', 'C0'].map(a => fmt(ir(name, a))).join(' | ')} |`);
  }
  line('');
}

// Path-activation oracle (R30-8): the arms took the labelled mechanism.
line('### Path-activation oracle (per arm, from the oracle binary of the same source)');
line('');
line('| Cell | Arm | pending_words_visited | summary_words_visited | summary_hint_loads | summary_hint_rmw | routed_scans |');
line('|---|---|---:|---:|---:|---:|---:|');
const show = v => (v === null || v === undefined ? 'n/a' : fmt(BigInt(v)));
for (const name of ['multiseg_cold_256k', 'seg_cycle_decommit_256k', 'growth16_n', 'r19_prf01_publication', 'r19_prf01_joined_producer_same_word', 'r20_prf01_c3_producer_distinct_words', 'r20_prf01_strict_trim_payload']) {
  for (const arm of ['A1', 'B1']) {
    const o = row(name, arm).oracle;
    if (arm === 'B1' && ['multiseg_cold_256k', 'seg_cycle_decommit_256k', 'growth16_n'].includes(name)) {
      assert.equal(o.pending_words_visited, 0);
      assert.ok(o.summary_words_visited > 0);
    }
    if (arm === 'B1' && name === 'r19_prf01_joined_producer_same_word') {
      assert.equal(o.summary_hint_loads, 4096);
      assert.equal(o.summary_hint_rmw, 64);
    }
    if (arm === 'B1' && name === 'r20_prf01_c3_producer_distinct_words') {
      assert.equal(o.summary_hint_loads, 4096);
      assert.equal(o.summary_hint_rmw, 4096);
    }
    if (arm === 'B1') {
      const a = BigInt(row(name, 'A1').oracle.pending_words_visited);
      const b = BigInt(o.pending_words_visited);
      rec(`oracle pending_words_visited: ${name}`, 'A1', 'B1', a, b, b - a, null, 'mechanism delta (counts)', true);
    }
    line(`| \`${name}\` | ${arm} | ${show(o.pending_words_visited)} | ${show(o.summary_words_visited)} | ${show(o.summary_hint_loads)} | ${show(o.summary_hint_rmw)} | ${show(o.routed_scans)} |`);
  }
}
line('');
for (const s of verdict.tables.size) {
  assert.equal(s.A, input.sizeOf.A);
  assert.equal(s.B, input.sizeOf.B);
  line(`\`size_of::<SmallSidecar>()\`: A ${s.A}, B ${s.B}, Δ ${s.numerator} (expected ${s.expected}) — ${s.pass ? 'pass' : 'FAIL'}.`);
}
line('');

// Failure list, straight from the verdict.
const failures = verdict.tables.iai.filter(r => !r.pass);
const failCells = [...new Set(failures.map(r => r.name))];
line(`Failed iai pairs: ${failures.length} of ${verdict.tables.iai.length}, in ${failCells.length} cells: ${failCells.map(n => `\`${n}\``).join(', ')}.`);

if (csvMode) {
  const header = ['report', 'base_commit', 'candidate_commit', 'features', 'host', 'valgrind', 'rustc', 'check',
    'arm_a', 'arm_b', 'value_a', 'value_b', 'delta', 'denominator', 'limit', 'verdict'];
  const features = row('multiseg_cold_256k', 'B1').features.join(' ');
  const fixed = ['R20_PRF01_C3_RUN01_REPORT', baseCommit, candidateCommit, features, host, valgrind, rustc.split(' (')[0]];
  const cell = v => (/[",]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
  const lines = [header.join(','), ...records.map(r => [...fixed, ...r].map(cell).join(','))];
  process.stdout.write(lines.join('\n') + '\n');
} else {
  process.stdout.write(out.join('\n') + '\n');
}
