#!/usr/bin/env node
// B4 A3 summary: derives the cross-class transfer report table (docs/perf/
// B4_A3_CROSS_CLASS.md) verbatim from the raw probe logs in
// docs/perf/b4_pmu/_raw_*.txt (measured on the b4-pmu branch, probe
// examples/b4_pmu_probe.rs — run scripts live on that branch).
//
// Outputs medians per scenario with asserts; the report table in
// docs/perf/B4_A3_CROSS_CLASS.md is this script's stdout, verbatim.
import { readFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "docs/perf/b4_pmu";
const out = [];
const say = (s) => { console.log(s); out.push(s); };

function readLines(name) {
  const txt = readFileSync(join(DIR, name), "utf8");
  const lines = txt.split(/\r?\n/).filter((l) => l.trim().length > 0);
  assert(lines.length > 0, `${name}: empty`);
  return lines;
}
function assert(cond, msg) {
  if (!cond) { console.error(`ASSERT FAILED: ${msg}`); process.exit(1); }
}
function median(arr) {
  assert(arr.length > 0, "median of empty array");
  const s = [...arr].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}
function fmt(x) { return x.toFixed(3).replace(/0$/, "").replace(/\.$/, ".0"); }

// --- interleave single-class: `inter live size portion pollute sefer_ticks mi_ticks [checksum]`
const inter = readLines("_raw_windows_interleave.txt").map((l) => l.trim().split(/\s+|,/));
for (const p of inter) assert(p.length >= 7 && p[0] === "inter", `interleave: bad line "${p}"`);

function interRows(live, size, portion) {
  return inter
    .filter((p) => Number(p[1]) === live && Number(p[2]) === size && Number(p[3]) === portion)
    .map((p) => ({ sefer: Number(p[5]), mi: Number(p[6]) }));
}
assert(interRows(256, 16, 128).length >= 3, "interleave: too few single-class churn rows (live=256 size=16 portion=128)");
const single = interRows(256, 16, 128);
const singleSefer = median(single.map((r) => r.sefer));
const singleMi = median(single.map((r) => r.mi));
assert(singleSefer >= 20 && singleSefer <= 23, `single-class sefer median ${singleSefer} out of expected 20..23 ticks/op`);
assert(singleMi >= 38 && singleMi <= 42, `single-class mi median ${singleMi} out of expected 38..42 ticks/op`);

// --- mixed (two sizes over ONE ring): `inter live 16/64 portion pollute sefer mi [checksum]`
const mixed = readLines("_raw_windows_mixed.txt").map((l) => l.trim().split(/\s+|,/));
for (const p of mixed) assert(p.length >= 7 && p[0] === "inter", `mixed: bad line "${p}"`);
const mixed128 = mixed.filter((p) => p[2] === "16/64" && Number(p[3]) === 128).map((p) => ({ sefer: Number(p[5]), mi: Number(p[6]) }));
assert(mixed128.length >= 3, "mixed: too few rows with portion=128");
const mixedSefer = median(mixed128.map((r) => r.sefer));
const mixedMi = median(mixed128.map((r) => r.mi));
assert(mixedSefer >= 32 && mixedSefer <= 40, `mixed sefer median ${mixedSefer} out of expected 32..40 ticks/op`);
assert(mixedMi >= 17 && mixedMi <= 21, `mixed mi median ${mixedMi} out of expected 17..21 ticks/op`);

// --- perf stat IPC: `who live ops counter value` (ops=0 is the idle baseline)
const stat = readLines("_raw_linux_perf_stat.txt").map((l) => l.trim().split(/\s+|,/));
function counters(who, live) {
  const m = {};
  for (const p of stat) {
    if (p[0] !== who || Number(p[1]) !== live) continue;
    assert(p.length >= 5, `perf_stat: bad line "${p}"`);
    m[p[3]] = Number(p[4]);
  }
  return m;
}
function ipc(who, live) {
  const c = counters(who, live);
  assert(c["cycles:u"] > 0 && c["instructions:u"] > 0, `perf_stat: missing cycles/instructions for ${who} live=${live}`);
  return c["instructions:u"] / c["cycles:u"];
}
const ipcSefer = {};
for (const live of [1, 64, 256, 4096]) ipcSefer[live] = ipc("sefer", live);
assert(ipcSefer[256] >= 4.0 && ipcSefer[256] <= 5.0, `sefer IPC live=256 ${ipcSefer[256]} out of expected 4.0..5.0`);
assert(ipcSefer[4096] >= 4.0 && ipcSefer[4096] <= 5.0, `sefer IPC live=4096 ${ipcSefer[4096]} out of expected 4.0..5.0`);

say("# B4 A3 cross-class transfer — medians from docs/perf/b4_pmu/_raw_*.txt (generated by scripts/b4_pmu_summary.mjs)");
say(`# scenario rows: single-class n=${single.length}, mixed-16/64-portion128 n=${mixed128.length}, perf_stat lives=${Object.keys(ipcSefer).join(",")}`);
say("");
say("| Scenario | sefer ticks/op (median) | mimalloc ticks/op (median) |");
say("|---|---:|---:|");
say(`| single-class churn L=256, size=16, portion=128 (${single.length} rows) | ${fmt(singleSefer)} | ${fmt(singleMi)} |`);
say(`| mixed 16/64 over ONE ring, portion=128, pollute=0 (${mixed128.length} rows) | ${fmt(mixedSefer)} | ${fmt(mixedMi)} |`);
say("");
say("| sefer perf stat IPC (instructions:u / cycles:u, live sweeps) | IPC |");
say("|---|---:|");
for (const live of [1, 64, 256, 4096]) say(`| live=${live} | ${ipcSefer[live].toFixed(2)} |`);
