#!/usr/bin/env node
// G1-K3: PMU base vs variant, sefer arm, from two raw logs of
// docs/perf/g1_pmu/k3/g1_fe.sh. Median over repeats per (scenario, event);
// `cycles` pools all three event groups. Prints variant/base per event.
// Usage: node scripts/g1_fe_compare.mjs <base.log> <variant.log> [--csv <out>]
import fs from "node:fs";

const args = process.argv.slice(2);
const csvAt = args.indexOf("--csv");
const csvOut = csvAt >= 0 ? args.splice(csvAt, 2)[1] : null;
const [baseLog, varLog] = args;
if (!baseLog || !varLog) throw new Error("usage: g1_fe_compare.mjs <base.log> <variant.log> [--csv <out>]");

function load(f) {
  const m = new Map();
  const add = (k, v) => {
    if (!Number.isFinite(v)) throw new Error(`${f}: not a number for ${k}`);
    if (!m.has(k)) m.set(k, []);
    m.get(k).push(v);
  };
  let identity = null;
  for (const l of fs.readFileSync(f, "utf8").split("\n")) {
    const x = l.trim().split(/\s+/);
    if (x[0] === "identity") identity = x[1];
    if (x[0] === "EV") add(`${x[2]}|${x[5].replace(/:u$/, "")}`, Number(x[6]));
    if (x[0] === "RUN") add(`${x[2]}|ns/op`, Number(x[x.length - 2]));
  }
  if (!identity) throw new Error(`${f}: identity line missing`);
  return { m, identity };
}
const med = (v) => {
  const s = [...v].sort((p, q) => p - q);
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};
const A = load(baseLog), B = load(varLog);
const keys = [...A.m.keys()].sort();
if (keys.length !== B.m.size || !keys.every((k) => B.m.has(k))) throw new Error("event sets differ");
console.log(`# G1-K3 PMU, sefer arm: base ${A.identity} vs variant ${B.identity}; median of repeats (generated by scripts/g1_fe_compare.mjs)`);
console.log("");
console.log("| scenario | event | base | variant | variant/base |\n|---|---|---:|---:|---:|");
const rows = [];
for (const k of keys) {
  const a = med(A.m.get(k)), b = med(B.m.get(k));
  const [s, e] = k.split("|");
  const r = a === 0 ? NaN : b / a;
  console.log(`| ${s} | ${e} | ${a.toPrecision(6)} | ${b.toPrecision(6)} | ${Number.isFinite(r) ? r.toFixed(3) : "—"} |`);
  rows.push([s, e, a, b, r]);
}
if (csvOut) fs.writeFileSync(csvOut, ["scenario,event,base,variant,ratio", ...rows.map((r) => r.join(","))].join("\n") + "\n");
