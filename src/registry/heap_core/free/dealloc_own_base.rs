/// Task #2002 (registry review): outcome of [`small_free_guard`], the guard
/// chain shared verbatim between [`HeapCore::dealloc_own_thread_with_base`]
/// and [`HeapCore::dealloc_batch_small`] (`free/dealloc_batch.rs`). Before
/// this task the two functions carried independent, hand-copied bodies of
/// this exact guard chain — `dealloc_batch_small`'s own copy was MISSING the
/// F7 branch (A) promoted-Large-block routing entirely (it only had branch
/// B's simpler `hardened`-only no-op), a real, reachable correctness gap
/// under `medium-classes` promotion without `hardened` (a legitimate
/// promoted-and-grown Large block freed via `dealloc_batch` would fall
/// straight into the M2 oracles below and read/write the Large block's own
/// PAYLOAD bytes as bitmap state, exactly the corruption F7 exists to
/// prevent) — closed by this extraction, not a separate fix.
#[cfg(all(feature = "alloc-global", feature = "fastbin"))]
pub(super) enum SmallFreeGuard {
    /// All guards passed. `off` is the block's segment-relative offset,
    /// already computed here so the caller does not re-derive it for the
    /// magazine push that follows.
    Accept { off: u32 },
    /// Rejected as a benign no-op (double-free / interior-pointer /
    /// hardened Large-kind contract violation) — already fully handled; the
    /// caller does nothing further for this pointer. (R6-T55: the callers
    /// bump the `LOCAL_REJECT_FREES` diagnostic here.)
    RejectNoOp,
    /// F4 (review): identical no-op handling to [`SmallFreeGuard::RejectNoOp`]
    /// (the block is not freed, nothing else happens) but the callers do NOT
    /// bump `LOCAL_REJECT_FREES` — this is the base's wrong-class
    /// Accept-branch reject (`divides`-passing, `small_class_matches`-failing
    /// / the state byte's class-field mismatch at an aligned LIVE granule),
    /// which returned without a counter increment. Reason classification
    /// happens only on this cold reject path; the hot accept path is
    /// untouched.
    RejectNoOpSilent,
    /// F7 branch (A) / the Ph3b pre-route: `ptr` is a LEGITIMATE
    /// promoted-and-grown Large block (`medium-classes` promotion). The
    /// caller MUST route `ptr`/`layout` to the REAL substrate free
    /// (`self.core.dealloc` — the SAME call the scalar
    /// `dealloc_own_thread_with_base` makes, per the Ph3b note in
    /// `dealloc_batch_small`) — this is a correctness requirement, not a
    /// defensive guard; treating it as a no-op leaks the segment (see this
    /// module's doc comment history, F7/R14-4/R17-4/R18-3/R19-1).
    ///
    /// `#[cfg_attr]`: Ph3b added a pre-route (see the function body) that
    /// constructs this variant under EVERY non-`hardened` build in which the
    /// F7 branches (A)/(B) both compile out — `medium-classes` promotion AND
    /// plain `production` alike. So the only genuinely unconstructing
    /// configuration left is `hardened` without the promotion predicate,
    /// which is branch (B)'s (already hand-written) reject shape.
    // R6-T20: this `cfg_attr`'s `not(...)` predicate is the ONE promotion
    // predicate copy that must stay hand-written: a `cfg_attr` argument
    // cannot invoke a macro, and a macro invocation is not allowed between
    // enum variants at all. It only toggles a dead-code ALLOW (a lint), so
    // a divergent copy can never silently include or exclude code; the
    // code-inclusion gates in this file are macro-generated instead.
    #[cfg_attr(
        not(all(
            feature = "medium-classes",
            any(
                not(feature = "exact-span-large"),
                all(feature = "large-reserved-capacity", not(feature = "numa-aware"))
            )
        )),
        allow(dead_code)
    )]
    RouteToLargeFree,
}

/// Task #2002: the shared F7/H1/M2 guard chain both
/// [`HeapCore::dealloc_own_thread_with_base`] and
/// [`HeapCore::dealloc_batch_small`] apply to a small-classified free BEFORE
/// it may be pushed into the magazine. Self-less (no `&self`/`&mut self`
/// needed — every check reads only `base`'s own segment metadata, the
/// caller-supplied `layout`, or the process-global `HARDENED_LARGE_NOOP_COUNT`
/// stat), so both callers — one taking `&mut self`, one operating inside a
/// batch loop — can call it identically.
///
/// Guard-by-guard, in the SAME load-bearing order the two call sites
/// previously duplicated by hand (do NOT reorder — each guard's own comment
/// in the function body states why):
///
/// 1. **F7 branch (A)** (task #25; R17-4/task #321; R18-3/task #330;
///    `medium_promotion_reachable!`-gated): `class_for` classifies a free on
///    the caller's *layout*, not on where `ptr` actually lives — under
///    `medium-classes`, R14-4's medium→Large promotion (task #289) diverts a
///    medium block to a dedicated Large segment at the 256 KiB threshold,
///    then OPT-G grows it IN PLACE up to `SMALL_MAX` while it stays a Large
///    segment; its dealloc layout (the post-grow size) classifies small even
///    though the block lives in a Large segment. So THIS routing to the real
///    substrate free is a CORRECTNESS REQUIREMENT, not a defensive guard:
///    without it the free falls into the M2 oracles below and reads/writes
///    bitmap state out of the Large allocation's own PAYLOAD bytes — the
///    segment is also never released (leaks; every subsequent promotion
///    reserves a fresh one, the R14-4 gate §2.2 anomaly). Under `hardened`,
///    R19-1 (task #337) additionally verifies the caller's layout is
///    consistent with the segment's CURRENT `large_size`/`large_align`
///    (foreign publication uses independent route metadata and never
///    reaches this local guard) before trusting this as the
///    legitimate case — a mismatch degrades to the SAME counted no-op branch
///    (B) uses, instead of really freeing a pointer a contract-violating
///    caller fabricated. Non-hardened builds make no such defence promise
///    and skip the consistency check (unmeasured perf/behavior change risk
///    on the production hot path). Ph3b dropped the `layout.size() >=
///    MEDIUM_REALLOC_PROMOTION_THRESHOLD` term that used to ride inside this
///    `if`: the physical kind alone decides now, because a
///    promoted-and-grown block can be freed with a layout BELOW the
///    threshold. The `cfg!(feature = "hardened")` widening itself (a contract
///    violation can use ANY small layout, not just a >= threshold one) stays,
///    and stays pinned RED by `regression_hardened_large_kind_own_free`
///    (2 MiB Large freed with a 64-byte layout aliased via the magazine when
///    the size gate skipped `kind_at`).
/// 2. **F7 branch (B)** (`hardened && !promotion-reachable`, R18-3 task
///    #330): when promotion is compiled OUT, a legitimate
///    Large-with-small-layout is structurally unreachable, but the
///    ILLEGITIMATE case (a `GlobalAlloc`-contract violation) is still
///    reachable — any Large-segment hit under a small-classified `layout`
///    is a counted no-op. Mutually exclusive with branch (A) by
///    construction (branch (A) requires promotion ON; branch (B) requires
///    promotion OFF) — together they cover every `hardened` build and every
///    promotion build. Under plain `production` (neither `hardened` nor
///    promotion) BOTH compile out and the Ph3b pre-route above takes over
///    instead, paying the single `BlockKind`/`kind_at` read it needs.
///    R22-12 (task #363) shares ONE counter (`HARDENED_LARGE_NOOP_COUNT`)
///    between both branches' rejection paths.
/// 3. **H1** (task #167, `hardened`): a block start of class `c` always
///    sits at a segment offset that is a whole multiple of `block_size(c)`
///    (carve aligns the bump to `block_size`) — an INTERIOR pointer
///    (`off % block_size(c) != 0`) is BLIND to the M2 byte oracle below
///    (the state byte is indexed at 16 B granularity, so an interior
///    offset that is still 16 B-aligned reads the START granule's
///    `encode(c, LIVE)` byte, falling through to a push that later hands
///    out a mid-block address — silent aliasing). Rejected as a no-op. Costs a
///    real `%` by a non-power-of-two divisor (~tens of cycles) on every
///    small free, so `hardened`-gated (never on the production hot path).
/// 4. **M2 oracle 1 — in-magazine double-free** (Э6, P6.1; always): an O(1)
///    scan of the magazine's resident slots (the former RAD-5/E4 residency
///    bitmap became the per-granule state byte with B4 (в)), replacing the
///    pre-Э6 per-heap-key-stamped-into-the-block-body filter design, which
///    was UNSOUND under user writes (a user write to the stamped bytes made
///    a later double-free skip the oracle and double-issue the pointer).
///    `off`/`meta` computed here are reused by the byte oracle below.
/// 5. **M2 oracle 1.5** (always): uncarved/stale-free (`off >= bump`) — a
///    block carved into a segment later decommitted+reset has `off >= bump`
///    (the reset zeroed the state bytes, so the byte oracle below would NOT
///    catch it); parity with `dealloc_small` (`alloc_core.rs`).
/// 6. **M2 oracle 2 — the state byte** (always): the exact
///    `encode(class, LIVE)` compare, catching an in-magazine OR
///    flushed-then-double-freed block (any non-LIVE byte — MAG, FREE or
///    zero — rejects). Order 4-then-6 is load-bearing (unflushed resting
///    place first, flushed resting place second) — do NOT reorder.
///
/// **Residual M2 limit:** these guards recognize current magazine residency
/// and free-list state, not an earlier allocation instance. They do not
/// guarantee detection of own-thread duplicate free/reissue before a pending
/// sidecar record is reclaimed. That schedule violates the unsafe deallocation
/// contract. Task #164/X7's ring guard and residual-test references are
/// historical, not current coverage; see
/// `RING_MAGAZINE_XTHREAD_DOUBLE_FREE_FIX.md` §8.4 for that design history.
#[cfg(all(feature = "alloc-global", feature = "fastbin"))]
#[inline(always)]
pub(super) fn small_free_guard(
    base: *mut u8,
    ptr: *mut u8,
    c: usize,
    layout: Layout,
) -> SmallFreeGuard {
    #[cfg(feature = "hardened")]
    use crate::alloc_core::size_classes::SizeClasses;

    // R6-T16: `layout` is consumed only by the promotion-routed branch (A)
    // below; shim the unused-parameter lint exactly where that branch
    // compiles out (the macro is the predicate's single textual source).
    medium_promotion_unreachable! {
        let _ = layout;
    }

    let kind = BlockKind::of(base, Some(c));

    // ── Ph3b: physical-Large routing when the F7 branches do not ─────────
    // The segment header's `kind` byte — not the caller's layout, and not a
    // layout-size threshold — decides. Branches (A)/(B) below are
    // `medium_promotion_reachable!` / `hardened` gated, so under plain
    // `production` (neither `hardened` nor promotion) BOTH compile out and a
    // Large-segment block freed with a small-classified layout fell straight
    // through to the M2 oracles and the magazine push, reading and writing
    // the Large block's own PAYLOAD as bitmap state. This ONE extra arm
    // closes that gap with the SAME `BlockKind` read the F7 branches use,
    // and is compiled in exactly when neither of them is — no duplicated
    // `kind_at` read, and no second answer to "is this block Large".
    //
    // The predicate is the NEGATION of the F7 gate union
    // (`hardened || promotion`) — R6-T20: generated by the
    // `medium_promotion_unreachable!` macro, with the `alloc-global` +
    // `fastbin` + `not(hardened)` terms riding as ordinary `#[cfg]`
    // attributes inside the invocation (multiple cfg attributes AND).
    medium_promotion_unreachable! {
        #[cfg(feature = "alloc-global")]
        #[cfg(feature = "fastbin")]
        #[cfg(not(feature = "hardened"))]
        if matches!(&kind, BlockKind::Large) {
            // SEC-03: only this already-selected Large arm reads payload geometry.
            if crate::alloc_core::AllocCore::reject_large_interior_free(base, ptr) {
                return SmallFreeGuard::RejectNoOp;
            }
            return SmallFreeGuard::RouteToLargeFree;
        }
    }

    // ── F7 branch (A): promoted-Large routing (correctness-required) ──
    // See this function's own doc comment above (point 1) for the full
    // case-split rationale.
    medium_promotion_reachable! {
    {
        if matches!(&kind, BlockKind::Large) {
            if !cfg!(feature = "hardened")
                || (SegmentHeader::large_size_at(base) == layout.size().max(crate::alloc_core::size_classes::MIN_BLOCK)
                    && SegmentHeader::large_align_at(base) == layout.align())
            {
                // Preserve hardened layout rejection below: only a layout
                // accepted for Large routing reaches the address rejection.
                if crate::alloc_core::AllocCore::reject_large_interior_free(base, ptr) {
                    return SmallFreeGuard::RejectNoOp;
                }
                return SmallFreeGuard::RouteToLargeFree;
            }
            #[cfg(feature = "alloc-stats")]
            HARDENED_LARGE_NOOP_COUNT.fetch_add(1, core::sync::atomic::Ordering::Relaxed);
            return SmallFreeGuard::RejectNoOp;
        }
    }
    }

    // ── F7 branch (B): hardened-only, promotion unreachable ──
    // R6-T20: the `hardened ∧ not(<promotion-predicate>)` gate is generated
    // by the `medium_promotion_unreachable!` macro plus an ordinary
    // `#[cfg]` attribute inside the invocation (multiple cfg attributes
    // AND).
    medium_promotion_unreachable! {
        #[cfg(feature = "hardened")]
        {
            if matches!(&kind, BlockKind::Large) {
                #[cfg(feature = "alloc-stats")]
                HARDENED_LARGE_NOOP_COUNT.fetch_add(1, core::sync::atomic::Ordering::Relaxed);
                return SmallFreeGuard::RejectNoOp;
            }
        }
    }

    // ── R6-T33 (review R6-CR-7): an untrusted segment kind ──
    // A `kind` byte that is not a legitimate discriminant decodes to
    // `BlockKind::Unknown`. The substrate free (`mem_impl.rs`) treats the same
    // case as a no-op (reject-not-guess); the magazine path must not run the
    // M2 oracles below against a segment whose real kind it cannot trust —
    // they would read the state bytes and `bump` as if Small and hand the
    // block to the magazine. One compare on the already-read `kind`.
    if matches!(&kind, BlockKind::Unknown) {
        return SmallFreeGuard::RejectNoOp;
    }

    // ── H1 (task #167): interior-pointer guard (HARDENED) ──
    #[cfg(feature = "hardened")]
    {
        let off_h = (ptr as usize).wrapping_sub(base as usize);
        let bs = SizeClasses::block_size(c);
        if !off_h.is_multiple_of(bs) {
            return SmallFreeGuard::RejectNoOp;
        }
    }

    // ── M2 double-free guard (Э6, P6.1) — see
    // `dealloc_own_thread_with_base`'s doc comment for the full design
    // rationale (order is load-bearing: in-magazine, THEN stale-free, THEN
    // flushed-bitmap).
    let off = (ptr as usize - base as usize) as u32;
    let meta = SegmentMeta::new(base);
    let payload_start = if matches!(&kind, BlockKind::Primordial) {
        SegmentLayout::primordial_meta_end()
    } else {
        SegmentLayout::small_meta_end()
    };
    if (off as usize) < payload_start {
        return SmallFreeGuard::RejectNoOp;
    }
    // B4 variant (в): the M2 double-free oracles collapse into ONE check on
    // the authoritative STATE BYTE. The alignment check above (H1, hardened)
    // plus the byte's class field (encoded at every issue site) subsume the
    // former `divides`/`small_class_matches` class-identity precursor; the
    // single reject below covers both the in-magazine and the stale-free
    // double-free cases (state MAG or FREE ⇒ not the caller's LIVE block).
    // F1 (review, B4 state-byte): an UNCONDITIONAL misalignment reject. The
    // byte is indexed `off >> 4`, so an interior offset `p+1..p+15` (without
    // `hardened`'s H1 stride check) indexes the START granule `p` and reads
    // `encode(c, LIVE)` — it would sail into the magazine push with `p+8`.
    // The base rejected these via `SizeClasses::divides` in the Accept
    // branch; here the reject collapses into the same single hot branch as
    // the byte compare (one OR / one branch — the hot path does not grow).
    // With invariant И1 (zero at every non-start granule) the alignment check
    // plus the exact byte compare is equivalent to the former `divides` +
    // class-identity pair.
    // F4 (review): the reject-reason split lives ONLY on this cold path.
    // `MAG`/`FREE`/zero (state) rejects and the remaining former
    // `RejectNoOp` sources reject with the base's increment
    // (`RejectNoOp`). MISALIGNED rejects match the base exactly: it
    // classified them via `divides` in the Accept branch and returned
    // WITHOUT bumping `LOCAL_REJECT_FREES`. The same holds for an ALIGNED
    // byte whose state is LIVE but whose CLASS field differs — the base's
    // wrong-class Accept-branch reject. Both surface as
    // `RejectNoOpSilent` (callers treat it identically minus the counter).
    let byte = meta.state_byte().read(off);
    let expected = crate::alloc_core::state_byte::StateByte::encode(
        c,
        crate::alloc_core::state_byte::StateByte::LIVE,
    );
    if (off & (crate::alloc_core::size_classes::MIN_BLOCK as u32 - 1)) != 0 {
        return SmallFreeGuard::RejectNoOpSilent;
    }
    if byte != expected {
        if byte != 0 && (byte >> 6) == crate::alloc_core::state_byte::StateByte::LIVE {
            return SmallFreeGuard::RejectNoOpSilent;
        }
        if byte == 0 {
            if (off as usize) < meta.bump_of() {
                return SmallFreeGuard::RejectNoOpSilent;
            }
            return SmallFreeGuard::RejectNoOp;
        }
        return SmallFreeGuard::RejectNoOp;
    }
    if (off as usize) >= meta.bump_of() {
        return SmallFreeGuard::RejectNoOp;
    }

    SmallFreeGuard::Accept { off }
}

