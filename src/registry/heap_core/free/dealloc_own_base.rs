#[cfg(all(feature = "alloc-global", feature = "fastbin"))]
#[cold]
#[inline(never)]
fn route_to_large_free(core: &mut HeapCore, block: *mut u8, layout: Layout, root: *mut u8) {
    // SAFETY: this own-thread body is reached only
    // from `HeapCore::dealloc`, an `unsafe fn` whose
    // caller bound the block/layout to the free contract;
    // the witness retains the table-derived root.
    // The substrate routes by
    // `kind` (Large) and frees the segment via
    // `span_usable`, ignoring the layout.
    #[allow(unsafe_code)]
    // R6-MS-1/2: unsafe call into `AllocCore::dealloc_at_base`.
    unsafe {
        // PF-10: `root` is the table-derived canonical root from the
        // `OwnedBlock` witness; do not re-resolve it in the substrate.
        // The entry `debug_assert_eq!(canonical_root_for(block), Some(root))`
        // already proves the precondition.
        core.core.dealloc_at_base(block, layout, root)
    };
}

impl HeapCore {
    /// Own-thread free consumes a table-derived root/block witness without
    /// repeating the mutable canonical lookup. The allocation stays live
    /// until this call; magazine and bitmap guards are unchanged.
    ///
    /// Only compiled under fastbin (the magazine path).
    #[cfg(all(feature = "alloc-global", feature = "fastbin"))]
    #[inline(always)]
    pub(crate) fn dealloc_own_thread_with_base(&mut self, owned: OwnedBlock, layout: Layout) {
        let (root, block) = (owned.root(), owned.block());
        debug_assert_eq!(self.core.canonical_root_for(block), Some(root));
        {
            use crate::alloc_core::size_classes::{SizeClasses, MIN_BLOCK};
            use crate::registry::heap_core::state::tcache::{FREE_PARK_CAP, TCACHE_CAP};
            let size = layout.size().max(MIN_BLOCK);
            let align = layout.align();
            // C1 (0.3.0): gate removed — see the matching comment in `alloc`'s
            // magazine fast path above for the full soundness argument
            // (`class_for` guarantees `block_size % align == 0` for any
            // `Some(c)` it returns, so keying the magazine by class alone is
            // sound for any align it accepted, not just align<=16).
            //
            // Ph3b: the class is computed first because the magazine push
            // below needs it, but it NO LONGER decides Small-vs-Large —
            // `small_free_guard` does, from the segment header's `kind` byte
            // via `BlockKind` (see its F7 branch and the pre-route above it).
            {
                if let Some(c) = SizeClasses::class_for(size, align) {
                    let cnt = self.tcache.classes[c].count as usize;

                    // Task #2002: F7 (task #25; R17-4/task #321; R18-3/task
                    // #330) Large-kind routing, H1 (task #167) interior-pointer
                    // guard, and the M2 (Э6, P6.1) double-free oracle pair —
                    // now the shared `small_free_guard` this file defines
                    // above, called identically from `dealloc_batch_small`
                    // (`free/dealloc_batch.rs`). See that function's doc
                    // comment for the full guard-by-guard rationale (case
                    // split for F7's legitimate-promotion vs. contract-
                    // violation branches, H1's interior-pointer blind spot in
                    // the M2 oracles, the Э6 double-free-oracle redesign
                    // history, and the RESIDUAL M2 LIMIT this pair does NOT
                    // cover — task #164/X7).
                    let (off, meta) = match small_free_guard(root, block, c, layout) {
                        SmallFreeGuard::Accept { off } => {
                            // B4 variant (в): the state byte encodes the class
                            // at every issue site, and `small_free_guard`
                            // requires an exact LIVE match on (class, state) —
                            // the former `small_class_matches`/`divides`
                            // class-identity re-check is subsumed.
                            (off, SegmentMeta::new(root))
                        }
                        SmallFreeGuard::RejectNoOp => {
                            // R6-T55: local no-op reject — internal counter,
                            // not the public foreign/unroutable stat. The
                            // guard's Large-interior cases surface HERE, so
                            // this is one increment per rejected free.
                            #[cfg(any(feature = "internals", feature = "bench-internals"))]
                            crate::alloc_core::LOCAL_REJECT_FREES
                                .fetch_add(1, core::sync::atomic::Ordering::Relaxed);
                            return;
                        }
                        // F4: the base's wrong-class Accept-branch reject did
                        // not bump the counter — same no-op, no increment.
                        SmallFreeGuard::RejectNoOpSilent => {
                            return;
                        }
                        SmallFreeGuard::RouteToLargeFree => {
                            route_to_large_free(self, block, layout, root);
                            return;
                        }
                    };

                    // R1-01: free-side byte budget. `cap` is `TCACHE_CAP` for
                    // small classes (unchanged behaviour) and smaller for
                    // large small-classes, mirroring D3's refill-side budget
                    // — see `FREE_PARK_CAP`'s doc comment.
                    let cap = FREE_PARK_CAP[c] as usize;
                    if cnt < cap {
                        // Legit free → push. NO key stamp, NO block-body write.
                        //
                        // B4 variant (в): mark this block MAG in the state
                        // byte (was RAD-5's magazine-bitmap set).
                        meta.state_byte().write(
                            off,
                            c,
                            crate::alloc_core::state_byte::StateByte::MAG,
                        );
                        // R6-T13: identity mask (`cnt < cap <= TCACHE_CAP`); skips bounds check.
                        self.tcache.classes[c].slots[cnt & (TCACHE_CAP - 1)] = block;
                        self.tcache.classes[c].count = (cnt + 1) as u8;
                        // R13-3 (task #273): a pushed-back block was
                        // previously issued (it is being FREED right now) —
                        // by the dispatch conjunct (§2 of both virgin-skip
                        // design docs) it is NEVER virgin, regardless of the
                        // bit any earlier occupant of physical slot `cnt`
                        // left behind. `PerClass::virgin_mask`'s own
                        // invariant ("bits >= count are 0") already
                        // guarantees bit `cnt` reads 0 here (it was `>=
                        // count` the instant before this push bumped
                        // `count`) — this is a defensive no-op AND, not a
                        // load-bearing clear, kept explicit so the invariant
                        // is visibly re-asserted at every mutation site
                        // rather than relying on readers to re-derive it.
                        #[cfg(feature = "virgin-zero-skip")]
                        {
                            self.tcache.classes[c].virgin_mask &= !(1u16 << cnt);
                        }
                        return;
                    }
                    // B1-c: magazine full (depot park, R1-01 swap-top, overflow
                    // half-flush) runs out of line, so the push fast path above
                    // keeps no callee-saved registers. Same order, same guards.
                    self.free_magazine_full(c, cnt, off, root, block);
                    return;
                }
            }
        }
        // Large / non-small / non-fastbin: free directly at the witness root.
        // PF-10: `root` is the table-derived canonical root from the
        // `OwnedBlock` witness; do not re-resolve it in the substrate.
        // SAFETY: dealloc/realloc callers keep the witnessed allocation live
        // and bind its block/layout to the free contract. The magazine guards
        // returned above for small fastbin blocks. The entry
        // `debug_assert_eq!(canonical_root_for(block), Some(root))` proves the
        // precondition.
        #[allow(unsafe_code)] // R6-MS-1/2: unsafe call into `AllocCore::dealloc_at_base`.
        unsafe {
            self.core.dealloc_at_base(block, layout, root)
        };
    }
}

#[cfg(all(feature = "alloc-global", feature = "fastbin"))]
impl HeapCore {
    /// The full-magazine tail of [`dealloc_own_thread_with_base`](Self::dealloc_own_thread_with_base)
    /// (B1-c): `small_free_guard` already accepted `block` (class `c`, offset
    /// `off` in the segment at `root`) and the push found `cnt == FREE_PARK_CAP[c]`.
    #[cold]
    #[inline(never)]
    fn free_magazine_full(
        &mut self,
        c: usize,
        cnt: usize,
        off: u32,
        root: *mut u8,
        block: *mut u8,
    ) {
        use crate::registry::heap_core::state::tcache::{FLUSH_N, FREE_PARK_CAP, TCACHE_CAP};
        let cap = FREE_PARK_CAP[c] as usize;
        let meta = SegmentMeta::new(root);
        // B4 depot (DP-3): park the full magazine whole (cold),
        // then `block` starts the next one. `block` itself is not
        // parked into a body-write path: only `slots` pointers move.
        // G1-K7: `depot_park` fills the floor, then the overflow within the
        // heap's budget; the inline gate skips the cold call once full. An
        // overflow park counts its decay event inside the cold helper, after
        // the ring owns the magazine; it touches only older records.
        if cnt == TCACHE_CAP && self.depot_may_park(c) && self.depot_park(c) {
            meta.state_byte()
                .write(off, c, crate::alloc_core::state_byte::StateByte::MAG);
            self.tcache.classes[c].slots[0] = block;
            self.tcache.classes[c].count = 1;
            // `depot_park` cleared the mask; `block` is not virgin.
            return;
        }
        // ── R1-01: free-side byte-budget cap reached ───────
        // `cnt == cap < TCACHE_CAP`: this class's per-refill byte
        // budget (`FREE_PARK_CAP`) is exhausted, but the physical
        // magazine array is not — do NOT grow past `cap` (that
        // would re-open the D3 gap: parking more bytes on the
        // free side than a refill ever would). O(1) swap-top:
        // the magazine evicts its TOP block to the substrate and
        // the currently-freed block takes its slot, so the
        // budget is preserved (depth stays at exactly `cap`).
        //
        // The flushed block must NOT be `block` itself: `block`'s
        // body still belongs to the live `Box::drop`/dealloc
        // frame (P1-box / item 164) — `flush_run` writes `next`
        // into the block body (`Node::write_next`), which is the
        // R1-01 UB. The evicted block has long been resident in
        // the magazine and its frame is complete, so writing its
        // body is safe. The M2 oracles (`small_free_guard`)
        // already ran above; their order is unchanged.
        if cap < TCACHE_CAP {
            let evicted = self.tcache.classes[c].slots[cnt - 1];
            // B4 (в): the evicted block LEAVES the magazine; its
            // MAG → FREE state-byte transition is committed by
            // `flush_run` inside the flush below (as on the
            // overflow path), so no separate clear happens here.
            debug_assert_eq!(
                self.core.canonical_root_for(evicted),
                Some(crate::alloc_core::os::segment_base_of_ptr(evicted)),
                "evicted magazine block must map to its segment base"
            );
            // SAFETY (R6-MS-3): `evicted` is a valid,
            // currently-live small-class-`c` allocation owned by
            // this heap's magazine (parked there by an earlier
            // free; its state byte reads MAG) — freed exactly
            // once here via a one-element batch, same guarantee
            // as the overflow path's flush of resident slots
            // below.
            #[allow(unsafe_code)] // R6-MS-3: unsafe call into `AllocCore::flush_class`.
            unsafe {
                self.core
                    .flush_class_internal(c, core::slice::from_ref(&evicted));
            }
            // The current block takes the evicted slot; `count`
            // is unchanged — the magazine still holds exactly
            // `cap` blocks (byte budget preserved).
            self.tcache.classes[c].slots[cnt - 1] = block;
            // B4 (в): the current block ENTERS the magazine —
            // commit LIVE → MAG (as on the push path above;
            // `meta`/`off` come from the guard). Metadata only:
            // the block body is not touched (R1-01).
            meta.state_byte()
                .write(off, c, crate::alloc_core::state_byte::StateByte::MAG);
            // R13-3 analogue: like the push path above, both the
            // current block (being FREED right now) and the
            // evicted block (previously issued from the
            // magazine) are NEVER virgin — defensive no-op AND,
            // kept explicit so the invariant is visibly
            // re-asserted at every mutation site.
            #[cfg(feature = "virgin-zero-skip")]
            {
                self.tcache.classes[c].virgin_mask &= !(1u16 << (cnt - 1));
            }
            #[cfg(feature = "bench-internals")]
            crate::alloc_core::unlocked_bump(
                &crate::registry::heap_core::diag::R1_01_CAP_ROUTE_FREES,
                1,
            );
            return;
        }
        // ── Magazine overflow (cnt == TCACHE_CAP) ──────────
        // P3 (task #147): the P7 dealloc-side bulk-mode bypass is
        // RETIRED together with the alloc-side bypass and the
        // `alloc_streak` counter. That branch fired only when the
        // alloc side had advanced the streak past BULK_THRESHOLD;
        // with the counter gone it could never fire, so keeping it
        // would be dead code guarded by a stuck-at-0 condition.
        // The always-taken half-flush + compact + push below is the
        // sole overflow policy now. D1/M2 unchanged: `flush_class`
        // returns blocks to the substrate via `dealloc_small`
        // (mark_free + dec_live) exactly as before.
        //
        // B4 variant (в): the former FLUSH_N magazine-bitmap
        // clear pre-pass is gone — `flush_class` itself commits
        // the LIVE/MAG → FREE transition via the state byte.
        // Normal overflow: half-flush, then push.
        // SAFETY (R6-MS-3): every slot in `slots[0..FLUSH_N]` is a
        // valid live small-class-`c` allocation owned by this core's
        // magazine (just freed into it under the alloc-xthread/fastbin
        // path); each is returned to the substrate exactly once here.
        #[allow(unsafe_code)] // R6-MS-3: unsafe call into `AllocCore::flush_class`.
        unsafe {
            self.core
                .flush_class_internal(c, &self.tcache.classes[c].slots[0..FLUSH_N])
        };
        // Compact: shift entries [FLUSH_N..CAP] down to [0..CAP-FLUSH_N].
        let remaining = TCACHE_CAP - FLUSH_N;
        for i in 0..remaining {
            self.tcache.classes[c].slots[i] = self.tcache.classes[c].slots[i + FLUSH_N];
        }
        // R13-3 (task #273): the virgin mask must undergo the
        // IDENTICAL shift as `slots` — bit `i` of the compacted
        // mask is bit `i + FLUSH_N` of the pre-compaction mask
        // (byte-identical to the `slots[i] = slots[i + FLUSH_N]`
        // loop just above, just on the bitmask instead of the
        // pointer array). The flushed low half (`slots[0..FLUSH_N]`,
        // now returned to the substrate via `flush_class`) is
        // dropped entirely, not merely cleared-and-kept.
        #[cfg(feature = "virgin-zero-skip")]
        {
            self.tcache.classes[c].virgin_mask >>= FLUSH_N;
        }
        // Push (Э6: NO key stamp, NO block-body write). The oracles
        // above already ran before this overflow branch, so a
        // double-free is caught even when the magazine is full.
        // RAD-5: mark the newly-pushed block magazine-resident.
        // B4 (в): MAG in the state byte.
        meta.state_byte()
            .write(off, c, crate::alloc_core::state_byte::StateByte::MAG);
        self.tcache.classes[c].slots[remaining] = block;
        self.tcache.classes[c].count = (remaining + 1) as u8;
        // R13-3: the newly-pushed block is a freed (previously
        // issued) block — never virgin (dispatch conjunct), same
        // reasoning as the non-overflow push arm above. Clear bit
        // `remaining` explicitly: after the `>>= FLUSH_N` shift
        // above, that bit holds whatever was at pre-shift index
        // `remaining + FLUSH_N` (`== TCACHE_CAP`, i.e. always 0 by
        // the mask invariant since no valid slot index reaches
        // `TCACHE_CAP`) — so this is defensive, not load-bearing,
        // matching the non-overflow arm's identical comment.
        #[cfg(feature = "virgin-zero-skip")]
        {
            self.tcache.classes[c].virgin_mask &= !(1u16 << remaining);
        }
    }
}
